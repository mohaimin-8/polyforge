"""Where the WP11 predictions miss: errors by cell factor (programme 2; descriptive).

score.py gives the agreement over all cells; this splits the signed and the
absolute error of attainment and of mean latency by each factor of the
design (cells.json): small pods, mid pods, cache, stream, and terciles of the
load target and the small-tier share, for the primary prediction and the two
declared secondaries. The replica-scaling question in particular: if the
primary's error grows with the small pool while measured_capacity's does not,
the linear capacity is the miss. Descriptive only: 20 cells, no test.

    python diagnose.py --runs ../out/validation      # writes DIAGNOSE.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import score  # noqa: E402

VARIANTS = (("primary", None), ("measured_capacity", "measured_capacity"), ("steady_cache", "steady_cache"))


def cell_table(runs: Path, predictions: Path) -> pd.DataFrame:
    design = {c["cell"]: c for c in json.loads((HERE / "cells.json").read_text(encoding="utf-8"))["cells"]}
    preds = {p["cell"]: p for p in json.loads(predictions.read_text(encoding="utf-8"))["predictions"]}
    rows = []
    for cell, c in design.items():
        valid = score.valid_runs(runs / f"cell{cell:02d}")
        if not valid:
            continue
        p = preds[cell]
        meas = [score.measure_run(r, p["slo_ms"], p["scored_s"]) for r in valid]
        row = {"cell": cell, "runs": len(valid), "small_pods": c["pools"][0], "mid_pods": c["pools"][1],
               "cache": c["cache"], "stream": c["stream"], "target_util": c["target_util"],
               "small_share": c["small_share"],
               "att_obs": float(np.nanmean([m["attainment"] for m in meas])),
               "mean_obs": float(np.nanmean([m["mean_latency_s"] for m in meas]))}
        for name, key in VARIANTS:
            q = p if key is None else p.get(key)
            if q is None:
                continue
            row[f"att_{name}"] = q["attainment"]
            row[f"mean_{name}"] = q["mean_latency_s"]
        rows.append(row)
    df = pd.DataFrame(rows)
    if len(df) >= 3:
        df["util_band"] = pd.qcut(df.target_util, 3, labels=["low", "mid", "high"])
        df["share_band"] = pd.qcut(df.small_share, 3, labels=["low", "mid", "high"])
    return df


def by_factor(df: pd.DataFrame, factor: str) -> list[str]:
    lines = [f"### {factor}", "", "| level | cells | " + " | ".join(
        f"att err {n} (signed / abs)" for n, _ in VARIANTS if f"att_{n}" in df) + " |",
             "|---|---:|" + "---|" * sum(1 for n, _ in VARIANTS if f"att_{n}" in df)]
    for level, g in df.groupby(factor, observed=True):
        cells = []
        for n, _ in VARIANTS:
            if f"att_{n}" in g:
                e = g[f"att_{n}"] - g.att_obs
                cells.append(f"{e.mean():+.3f} / {e.abs().mean():.3f}")
        lines.append(f"| {level} | {len(g)} | " + " | ".join(cells) + " |")
    return lines + [""]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--runs", type=Path, required=True)
    ap.add_argument("--predictions", type=Path, default=HERE / "predictions.json")
    ap.add_argument("--out", type=Path, default=HERE / "DIAGNOSE.md")
    args = ap.parse_args(argv)
    df = cell_table(args.runs, args.predictions)
    L = ["# WP11: where the predictions miss (descriptive)", "",
         f"Generated by `testbed/validation/diagnose.py` over {len(df)} cells with valid runs. Error = predicted "
         "minus measured attainment (a share of requests); signed mean / mean absolute value per level.", ""]
    if len(df) >= 3:
        for factor in ("small_pods", "mid_pods", "cache", "stream", "util_band", "share_band"):
            L += by_factor(df, factor)
    L += ["## Per cell", "", "| cell | runs | pools | cache | att measured | att primary | att measured_capacity | "
          "mean s measured | mean s primary | mean s measured_capacity |", "|---:|---:|---|---|---:|---:|---:|---:|---:|---:|"]
    for _, r in df.sort_values("cell").iterrows():
        L.append(f"| {r.cell} | {r.runs} | {r.small_pods}+{r.mid_pods} | {r.cache} | {r.att_obs:.3f} | "
                 f"{r.get('att_primary', np.nan):.3f} | {r.get('att_measured_capacity', np.nan):.3f} | "
                 f"{r.mean_obs:.2f} | {r.get('mean_primary', np.nan):.2f} | {r.get('mean_measured_capacity', np.nan):.2f} |")
    L.append("")
    args.out.write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
