"""Sobol indices of the coordination gain over plant 2's leading factors
(programme 2, WP5 global sensitivity, step 3; EXPLORATORY).

Factors: the K with the largest mu* of the gain in the Morris screen
(morris_pilot.py; data/morris_runs.csv.gz, the latest screen), the other
mode-B constants at their defaults; or --factors by name. Design: Saltelli's
sampling (SALib 1.6.0: a scrambled Sobol' sequence, N base points, first-order
and total indices, N x (K + 2) plants), each factor uniform over its WP5
range. Every plant runs the joint and the per-knob planner on the Morris
screen's 20 population workloads (tuning half, large cluster) with COMMON
random numbers: each workload's demand seed is the same for every plant (the
harness would otherwise derive it from the plant's own constants, mixing
demand noise into the plant's effect). J as morris_pilot scores it, with
programme 2's normalisation by the steps scored. Per plant: the gain
(per-knob J minus joint J, mean over workloads) and the joint J; indices S1
and ST with SALib's bootstrap 95 % intervals.

The plan's step 4 also re-tunes the comparators for every sampled plant. At
N x (K + 2) plants that is beyond the budget, and the comparators are not
part of the gain measured here, so this stage runs the two planner arms only,
as the Morris screen does; a claim about comparators is not made from it.

    python sobol.py [--n 128] [--k 6] [--workers 6]     # long: N x (K+2) x 40 runs
    python sobol.py --report-only
"""

from __future__ import annotations

import argparse
import dataclasses
import os
import sys
import time
from multiprocessing import Pool
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import morris_pilot as mp  # noqa: E402  (plant, harness and arms on the path)

SEED = 20261114
N_BASE = 128
K_FACTORS = 6
OUT = HERE / "data"


def morris_ranking(runs: pd.DataFrame) -> list[str]:
    """Factors by mu* of the gain, from a Morris screen's runs (its own design rebuilt from SEED)."""
    names = mp.factor_names_of(runs)
    k1 = len(names) + 1
    r = runs.plant.nunique() // k1
    traj = mp.trajectories(len(names), r, np.random.default_rng(mp.SEED))
    runs = runs.copy()
    runs["J"] = runs.J - runs.cost / (119 * 8) / 0.01 + runs.cost / (mp.SCORED_STEPS * 8) / 0.01
    wide = runs.pivot_table(index=["plant", "workload"], columns="system", values="J").reset_index()
    wide["gain"] = wide.x_decoupled - wide.x_joint
    per_plant = wide.groupby("plant").agg(gain=("gain", "mean")).reset_index()
    return list(mp.elementary_effects(per_plant, traj, names, "gain").factor)


def problem(chosen: list[str]) -> dict:
    by = {c.name: c for c in mp.factors()}
    unknown = [n for n in chosen if n not in by]
    if unknown:
        raise ValueError(f"no mode-B factor with a WP5 range named {unknown}")
    return {"num_vars": len(chosen), "names": chosen, "bounds": [list(by[n].sweep) for n in chosen]}


def jobs(X: np.ndarray, prob: dict) -> list[tuple]:
    workloads = mp.pw.names("tuning")[:mp.N_WORKLOADS]
    seeds = mp.common_seeds(workloads)
    out = []
    for pid, x in enumerate(X):
        values = dict(zip(prob["names"], (float(v) for v in x)))
        form, econ = mp.plant.mode_b(**values)
        spec = mp.hconfig.ExperimentSpec(
            name=f"wp5_sobol_{pid}", steps=120, reps=1, systems=["x_joint", "x_decoupled"],
            workloads=workloads, tenant_mixes=["own"], cluster_sizes=["large"], shared_seeds=True,
            timeseries_reps=0, model_form=form, economy=econ)
        out += [(pid, values, dataclasses.replace(run, seed=seeds[run.workload])) for run in mp.hconfig.expand(spec)]
    return out


def per_plant(runs: pd.DataFrame) -> pd.DataFrame:
    runs = runs.copy()
    runs["J"] = runs.J - runs.cost / (119 * 8) / 0.01 + runs.cost / (mp.SCORED_STEPS * 8) / 0.01
    wide = runs.pivot_table(index=["plant", "workload"], columns="system", values="J").reset_index()
    wide["gain"] = wide.x_decoupled - wide.x_joint
    return wide.groupby("plant").agg(gain=("gain", "mean"), J_joint=("x_joint", "mean")).reset_index()


def indices(Y: np.ndarray, prob: dict) -> pd.DataFrame:
    from SALib.analyze import sobol as sobol_analyze

    si = sobol_analyze.analyze(prob, Y, calc_second_order=False, seed=SEED)
    return pd.DataFrame({"factor": prob["names"], "S1": si["S1"], "S1_ci": si["S1_conf"],
                         "ST": si["ST"], "ST_ci": si["ST_conf"]}).sort_values("ST", ascending=False)


def report(pp: pd.DataFrame, prob: dict, n: int) -> str:
    L = ["# Sobol indices of the coordination gain (WP5 step 3; exploratory)", "",
         f"Generated by `research/sensitivity/sobol.py`: {prob['num_vars']} factors, Saltelli N = {n} "
         f"({len(pp)} plants), joint and per-knob planners on {mp.N_WORKLOADS} population workloads with common "
         f"random numbers. Gain (per-knob J minus joint J) mean {pp.gain.mean():+.4f}, range "
         f"{pp.gain.min():+.4f} to {pp.gain.max():+.4f}; share of plants with gain > 0: "
         f"{(pp.gain > 0).mean():.2f}.", ""]
    for col, title in (("gain", "coordination gain"), ("J_joint", "joint planner's J")):
        t = indices(pp.sort_values("plant")[col].to_numpy(), prob)
        L += [f"## {title}", "", "| factor | S1 [95 %] | ST [95 %] |", "|---|---:|---:|"]
        L += [f"| `{r.factor}` | {r.S1:+.3f} [{r.S1 - r.S1_ci:+.3f}, {r.S1 + r.S1_ci:+.3f}] | "
              f"{r.ST:.3f} [{r.ST - r.ST_ci:+.3f}, {r.ST + r.ST_ci:+.3f}] |" for r in t.itertuples()]
        L.append("")
    L.append("The two planner arms only; comparators were not re-tuned per plant (see the docstring).")
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    from SALib.sample import sobol as sobol_sample

    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--n", type=int, default=N_BASE)
    ap.add_argument("--k", type=int, default=K_FACTORS)
    ap.add_argument("--factors", nargs="*", default=None, help="factor names (default: Morris top K)")
    ap.add_argument("--workers", type=int, default=max(1, min(6, (os.cpu_count() or 2) - 2)))
    ap.add_argument("--report-only", action="store_true")
    args = ap.parse_args(argv)
    chosen = args.factors or morris_ranking(pd.read_csv(OUT / "morris_runs.csv.gz"))[:args.k]
    prob = problem(chosen)
    X = sobol_sample.sample(prob, args.n, calc_second_order=False, seed=SEED)
    partial = OUT / f"sobol_runs_n{args.n}_k{len(chosen)}.partial.csv"
    if not args.report_only:
        todo = jobs(X, prob)
        done = set()
        if partial.exists():
            prev = pd.read_csv(partial)
            done = set(zip(prev.plant, prev.system, prev.workload))
        todo = [j for j in todo if (j[0], j[2].system, j[2].workload) not in done]
        t0 = time.time()
        with Pool(args.workers) as pool:
            for i, row in enumerate(pool.imap_unordered(mp.run_one, todo, chunksize=4), 1):
                pd.DataFrame([row]).to_csv(partial, mode="a", header=not partial.exists(), index=False)
                if i % 200 == 0:
                    print(f"{i}/{len(todo)} runs, {time.time() - t0:.0f} s", flush=True)
    runs = pd.read_csv(partial)
    pp = per_plant(runs)
    if len(pp) != len(X):
        raise RuntimeError(f"{len(pp)} of {len(X)} plants finished; rerun to resume")
    runs.to_csv(OUT / "sobol_runs.csv.gz", index=False)
    text = report(pp, prob, args.n)
    (HERE / "SOBOL.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
