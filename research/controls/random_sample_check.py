"""H2 on the adversarial search's unselected half (WP22 follow-up; EXPLORATORY).

The search's first `random` regimes were drawn uniformly from the regime
space before any hill-climbing, so they are an unselected sample: the one
place in the search where a correlation between a predictor and the gain is
not manufactured by the search's own selection. This reports, on that half
only, the rank correlation of each per-decision predictor with the gain
(bootstrap intervals over regimes) and rank-regression R^2 for the index,
the one-step loss and the constraint-coupling rate (share of decisions that
start from an infeasible anchor).

    python random_sample_check.py      # writes RANDOM_SAMPLE_CHECK.md
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
PREDICTORS = {"I": "worst-case index", "I_quantile": "quantile index", "loss": "one-step loss",
              "costly": "share of costly disagreements", "anchor_infeasible": "share of infeasible anchors",
              "per_knob_infeasible": "share of infeasible per-knob combinations"}
DRAWS, SEED = 2000, 20261113


def spearman(a, b) -> float:
    return float(pd.Series(a).rank().corr(pd.Series(b).rank()))


def rank_r2(df: pd.DataFrame, cols: list[str]) -> float:
    y = df.G.rank().to_numpy()
    a = np.column_stack([np.ones(len(df))] + [df[c].rank().to_numpy() for c in cols])
    coef, *_ = np.linalg.lstsq(a, y, rcond=None)
    pred = a @ coef
    return float(1 - ((y - pred) ** 2).sum() / ((y - y.mean()) ** 2).sum())


def main() -> int:
    regimes = pd.read_csv(HERE / "data" / "adversarial_search_regimes.csv")
    rnd = regimes[regimes.phase == "random"].reset_index(drop=True)
    rng = np.random.default_rng(SEED)
    idx = rng.integers(0, len(rnd), size=(DRAWS, len(rnd)))
    L = ["# H2 on the unselected half of the adversarial search (exploratory)", "",
         f"Generated by `research/controls/random_sample_check.py` from `data/adversarial_search_regimes.csv`: "
         f"the {len(rnd)} regimes drawn at random before hill-climbing. Gain G = J(per-knob) - J(joint); "
         f"intervals are {DRAWS} bootstrap draws over regimes. G: mean {rnd.G.mean():+.4f}, median "
         f"{rnd.G.median():+.4f}, max {rnd.G.max():+.4f}.", "",
         "| predictor | Spearman with G | 95% interval |", "|---|---:|---|"]
    for col, label in PREDICTORS.items():
        boot = [spearman(rnd[col].to_numpy()[i], rnd.G.to_numpy()[i]) for i in idx]
        lo, hi = np.nanpercentile(boot, [2.5, 97.5])
        L.append(f"| {label} | {spearman(rnd[col], rnd.G):+.2f} | [{lo:+.2f}, {hi:+.2f}] |")
    L += ["", "| rank regression | R^2 |", "|---|---:|"]
    for cols in (["I"], ["loss"], ["anchor_infeasible"], ["I", "anchor_infeasible"], ["loss", "anchor_infeasible"]):
        L.append(f"| G ~ {' + '.join(cols)} | {rank_r2(rnd, cols):.3f} |")
    L += ["", "Reading: on unselected regimes the index ranks with the gain only weakly and the one-step loss "
          "somewhat better; the share of infeasible anchors, which carries most of the search's worst case "
          "(DIAGNOSE_158.md), does not rank with the gain in general. Exploratory: 100 regimes, panels of 4 "
          "design points, 60 steps.", ""]
    (HERE / "RANDOM_SAMPLE_CHECK.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
