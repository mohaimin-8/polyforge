"""A first specification curve: the WP9 tuning pilot re-scored under the
evaluation's scoring choices (programme 2, WP5 step 2; EXPLORATORY).

Scoring-only: the arms are NOT re-run per specification (the plan's full
curve re-runs every arm under its specification's objective); the evaluation
runs of `research/comparators/pilot/` are re-scored. Choices:

- plant: A (API-backed) or B (self-hosted pools)
- granularity: comparators tuned overall or per workload class
- comparator: per_knob, one_knob, layers, rules
- violation weight: 1, 2 (as scored so far), 4
- fairness weight: 0, 0.5 (as scored so far)
- quality price on mean answer-quality loss: 0 (as scored so far), 0.5, 1
- unserved price: 0, or 1 x the share of AI requests shed
- scale: absolute J difference, or log ratio (scale-free)

Effect per workload = score(comparator) - score(joint), positive = the joint
planner is better. The arms were tuned with violation weight 2, fairness
0.5 and no quality or unserved price; specifications that score other
weights evaluate tuned arms under an objective they were not tuned for,
which is one reason the full curve re-runs them.

    python pilot_curve.py      # writes SPEC_CURVE_PILOT.md and spec_curve_pilot.png
"""

from __future__ import annotations

import itertools
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from curve import curve_from_matrix, paired_matrix, plot, report, sign_flip_test  # noqa: E402

PILOT = HERE.parents[0] / "comparators" / "pilot"
TENANTS = 8
COST_SCALE = 0.01
CHOICES = {
    "plant": ["A", "B"],
    "granularity": ["overall", "per_class"],
    "comparator": ["per_knob", "one_knob", "layers", "rules"],
    "violation_weight": [1.0, 2.0, 4.0],
    "fairness_weight": [0.0, 0.5],
    "quality_price": [0.0, 0.5, 1.0],
    "unserved_price": [0.0, 1.0],
    "scale": ["absolute", "log"],
}


def evaluation_rows() -> pd.DataFrame:
    frames = []
    for plant in CHOICES["plant"]:
        (path,) = sorted(PILOT.glob(f"plant{plant}_own_*/runs.csv.gz"))
        df = pd.read_csv(path, float_precision="round_trip")
        df = df[df.phase == "evaluation"].copy()
        df["plant"] = plant
        frames.append(df)
    return pd.concat(frames, ignore_index=True)


def score(df: pd.DataFrame, spec: dict) -> pd.Series:
    s = (df.total_cost_usd / (df.steps * TENANTS) / COST_SCALE
         + spec["violation_weight"] * df.mean_violation
         + spec["fairness_weight"] * (1.0 - df.mean_jain)
         + spec["quality_price"] * df.mean_quality_loss
         + spec["unserved_price"] * df.ai_shed_request_share)
    return np.log(s) if spec["scale"] == "log" else s


def long_table(rows: pd.DataFrame) -> pd.DataFrame:
    names = list(CHOICES)
    out = []
    for combo in itertools.product(*(CHOICES[n] for n in names)):
        spec = dict(zip(names, combo))
        sub = rows[(rows.plant == spec["plant"]) & rows.granularities.str.contains(spec["granularity"])]
        for arm, label in (("joint", "joint"), (spec["comparator"], "comparator")):
            part = sub[sub.arm == arm]
            if part.workload.duplicated().any():
                raise ValueError(f"{spec}: several evaluation rows per workload for {arm}")
            out.append(pd.DataFrame({**{k: [v] * len(part) for k, v in spec.items()},
                                     "workload": part.workload.to_numpy(), "arm": label,
                                     "score": score(part, spec).to_numpy()}))
    return pd.concat(out, ignore_index=True)


def main() -> int:
    long = long_table(evaluation_rows())
    cols = list(CHOICES)
    specs, d = paired_matrix(long, cols, "joint", "comparator")
    c = curve_from_matrix(specs, d)
    test = sign_flip_test(d)
    plot(c, cols, HERE / "spec_curve_pilot.png",
         f"Joint vs per-layer comparators, {len(specs)} scoring specifications (WP9 pilot, exploratory)")
    by = {col: c.specs.assign(effect=c.effect).groupby(col).effect.median().to_dict() for col in cols}
    L = ["# Specification curve of the WP9 tuning pilot (scoring-only; exploratory)", "",
         "Generated by `research/speccurve/pilot_curve.py` from `research/comparators/pilot/`. The arms are "
         "re-scored, not re-run, under each specification; see the module docstring for the choices and "
         "what scoring-only cannot show. Plot: `spec_curve_pilot.png`.", "",
         f"**{len(specs)} specifications, {d.shape[1]} paired workloads each.** Median effect "
         f"{test['median_effect']:+.4f}; significant for the joint planner in "
         f"{test['share_significant_positive']:.0%} of specifications, against it in "
         f"{test['share_significant_negative']:.0%}. Whole-curve sign-flip test: p = "
         f"{test['p_median_positive']:.4f} (joint better), {test['p_median_negative']:.4f} (joint worse); "
         f"share significant for joint p = {test['p_share_positive']:.4f}, against p = "
         f"{test['p_share_negative']:.4f}.", "",
         "## Median effect by choice", "", "| choice | level | median effect |", "|---|---|---:|"]
    for col in cols:
        for level, value in by[col].items():
            L.append(f"| {col} | {level} | {value:+.4f} |")
    L += ["", "## The curve's ends (10 lowest and 10 highest effects)", ""]
    full = report(c, test, "joint", "comparator", cols).split("\n")
    header, rows = full[:4], full[4:4 + len(specs)]
    L += header + rows[:10] + ["| ... | ... |" + " ... |" * len(cols)] + rows[-10:]
    L += ["", "Positive effect = the joint planner scores better than the comparator on that specification.", ""]
    (HERE / "SPEC_CURVE_PILOT.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L[:40]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
