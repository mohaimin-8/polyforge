"""SHED_POOLED.md: request accounting pooled over requests (exploratory).

`RESULTS_SHED_ACCOUNTING.md` reports, as registered, each ratio averaged
over design points or windows. A ratio averaged over units of very different
volume is not the ratio over requests: on the BurstGPT windows, low-volume
windows dominate the mean. This script reports the pooled (volume-weighted)
ratios, recovered exactly from the committed exports of the SA reruns:

    served  = total_cost / cost_per_served_request
    offered = served / (1 - shed_request_share)
    shed    = offered * shed_request_share

EXPLORATORY: not in PREREG_SHED_ACCOUNTING; no test, no verdict.

    python analysis_shed_pooled.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from stats import record_path  # noqa: E402

RESULTS = HERE.parents[1] / "eval" / "results"
RECORD = "SHED_POOLED.md"
EXPORTS = {"Main matrix (JN runs)": "metrics_shed_jointness.csv.gz",
           "Real BurstGPT demand (TA runs)": "metrics_shed_trace.csv.gz"}
ARMS = ["jcac_converged", "jcac_decoupled", "jcac_tier_floor", "hpa_fair_capped", "keda_fair_capped",
        "layered_small_tuned", "static_share"]
UNIT = ["workload", "tenant_mix", "cluster_size"]
TREATMENT = "jcac_converged"


def recover(df: pd.DataFrame) -> pd.DataFrame:
    served = df.total_cost_usd / df.cost_per_served_request
    offered = served / (1.0 - df.shed_request_share)
    return df.assign(served=served, offered=offered, shed=offered * df.shed_request_share)


def section(title: str, df: pd.DataFrame) -> list[str]:
    df = recover(df)
    per_run = df.groupby(["system", "rep"] + UNIT).offered.first().groupby("system").mean()
    g = df.groupby("system")[["total_cost_usd", "served", "offered", "shed"]].sum()
    runs = df.groupby("system").size()
    L = [f"## {title}", "",
         f"Requests offered per run: {per_run[TREATMENT]:,.0f} (identical across arms: shared seeds, "
         f"spread {per_run.max() - per_run.min():.3g}).", "",
         "| arm | shed, all requests (pooled) | requests shed per run | $ per 1,000 served (pooled) |",
         "|---|---:|---:|---:|"]
    for arm in ARMS:
        r = g.loc[arm]
        L.append(f"| `{arm}` | {r.shed / r.offered:.1%} | {r.shed / runs[arm]:,.0f} | "
                 f"{1000.0 * r.total_cost_usd / r.served:.5f} |")
    unit = df.groupby(UNIT + ["system"]).cost_per_served_request.mean().unstack("system")
    L += ["", f"Units where `{TREATMENT}` costs less per request served (unit means): "
          f"vs `hpa_fair_capped` {int((unit[TREATMENT] < unit.hpa_fair_capped).sum())} of {len(unit)}, "
          f"vs `layered_small_tuned` {int((unit[TREATMENT] < unit.layered_small_tuned).sum())} of {len(unit)}.", ""]
    return L


def main() -> int:
    L = ["# Shed accounting pooled over requests (exploratory)", "",
         "Generated by `analysis_shed_pooled.py` from the committed SA exports. **Exploratory; not in "
         "`PREREG_SHED_ACCOUNTING.md`.** The registered record averages each ratio over units; here each "
         "ratio is taken over all requests of all runs (volume-weighted). Counts are recovered exactly from "
         "the exported cost, cost per served request and shed share.", ""]
    for title, export in EXPORTS.items():
        L += section(title, pd.read_csv(RESULTS / export, float_precision="round_trip"))
    out = record_path(RECORD)
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
