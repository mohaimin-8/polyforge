"""PREREG_CACHE_SENSITIVITY.md -> RESULTS_CACHE_SENSITIVITY.md.

The coordination test and the two practical comparisons under three cache-hit
curves (measured on LMSYS-Chat-1M, the paper's, and a high bound). FROZEN
with the pre-registration; the test rule is analysis_fair_j's, imported.

    python analysis_cache_sensitivity.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from analysis_fair_j import (  # noqa: E402
    ALPHA, BOOT_N, BOOT_SEED, DESIGN, complete_design_points, design_diffs, superiority,
)
from stats import holm_bonferroni, record_path  # noqa: E402

RESULTS = HERE.parents[1] / "eval" / "results"
RECORD = "RESULTS_CACHE_SENSITIVITY.md"
CURVES = {"measured": (0.285, 19), "published": (0.85, 256), "high": (0.95, 128)}
ARMS = ["jcac_converged", "jcac_decoupled", "hpa_fair_capped", "layered_small_tuned"]
TREATMENT = "jcac_converged"
EQ_MARGIN = 0.025
TENANTS, COST_SCALE_USD = 8, 0.01
COLUMNS = ["total_cost_usd", "mean_violation", "mean_jain", "mean_excess", "tier_none_step_share",
           "cache_hit_rate", "coordination_disagreement_share", "steps"]
KEYS = ["system", "workload", "tenant_mix", "cluster_size", "rep"]
SUPERIORITY = {"CS-H1": "hpa_fair_capped", "CS-H2": "layered_small_tuned"}


def db(curve: str) -> Path:
    return RESULTS / f"raw_sim_cache_{curve}.duckdb"


def export(curve: str) -> Path:
    return RESULTS / f"metrics_cache_{curve}.csv.gz"


def load(curve: str) -> pd.DataFrame | None:
    if db(curve).exists():
        import duckdb

        con = duckdb.connect(str(db(curve)), read_only=True)
        try:
            return con.execute(
                "select " + ", ".join(f"r.{c}" for c in KEYS) + ", " + ", ".join(f"m.{c}" for c in COLUMNS)
                + " from runs r join metrics m on r.run_id = m.run_id where r.status = 'valid'").fetchdf()
        finally:
            con.close()
    if export(curve).exists():
        return pd.read_csv(export(curve), float_precision="round_trip")[KEYS + COLUMNS]
    return None


def score_j(df: pd.DataFrame) -> pd.Series:
    return (df.total_cost_usd / (df.steps * TENANTS) / COST_SCALE_USD
            + 2.0 * df.mean_violation + 0.5 * (1.0 - df.mean_jain))


def ci(r: dict) -> str:
    return f"[{r['ci'][0]:+.4f}, {r['ci'][1]:+.4f}]"


def build(frames: dict[str, pd.DataFrame]) -> str:
    L = ["# Does the coordination result survive other cache-hit curves?", "",
         "Generated by `analysis_cache_sensitivity.py`, frozen with `PREREG_CACHE_SENSITIVITY.md`. Unit: the "
         "design point (reps averaged), listwise complete. J uses each run's own scored steps. PASS = one-sided "
         f"Wilcoxon at its Holm threshold AND the 95% bootstrap CI below 0 ({BOOT_N:,} resamples, seed {BOOT_SEED}). "
         f"EQUIVALENT = 95% CI inside ±{EQ_MARGIN} J. Negative ΔJ = JC better.", ""]
    prepared, tests, eqs, gains = {}, {}, {}, {}
    for curve, df in frames.items():
        n_all = df[["workload", "tenant_mix", "cluster_size"]].drop_duplicates().shape[0]
        df = complete_design_points(df, ARMS)
        df = df.assign(J=score_j(df))
        prepared[curve] = df
        n = df[["workload", "tenant_mix", "cluster_size"]].drop_duplicates().shape[0]
        hmax, half = CURVES[curve]
        L += [f"## Curve `{curve}`: h(c) = {hmax}·c/(c+{half}); {n} of {n_all} design points complete", "",
              "| arm | J | cost $ | violation | excess | Jain | cache hit | AI shed | disagreement |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for arm in ARMS:
            s = df[df.system == arm]
            L.append(f"| `{arm}` | {s.J.mean():.4f} | {s.total_cost_usd.mean():.3f} | {s.mean_violation.mean():.4f} | "
                     f"{s.mean_excess.mean():.4f} | {s.mean_jain.mean():.4f} | {s.cache_hit_rate.mean():.3f} | "
                     f"{s.tier_none_step_share.mean():.1%} | {s.coordination_disagreement_share.mean():.2%} |")
        L.append("")
        eqs[curve] = superiority(design_diffs(df, TREATMENT, "jcac_decoupled", "J"))
        gains[curve] = superiority(design_diffs(df, "jcac_decoupled", TREATMENT, "J"))
        for hid, b in SUPERIORITY.items():
            tests[f"{hid}[{curve}]"] = (b, superiority(design_diffs(df, TREATMENT, b, "J")))
    holm = holm_bonferroni({hid: r["p"] for hid, (_, r) in tests.items()}, ALPHA)
    L += ["## Coordination: joint − decoupled search, equivalence within ±0.025 J", "",
          "| id | ΔJ (joint − decoupled) | 95% CI | equivalent? | gain G = J(dec) − J(joint) as % of J(dec) |",
          "|---|---:|---|---|---:|"]
    for curve, r in eqs.items():
        eq = -EQ_MARGIN < r["ci"][0] and r["ci"][1] < EQ_MARGIN
        dec_j = prepared[curve][prepared[curve].system == "jcac_decoupled"].J.mean()
        L.append(f"| CS-EQ[{curve}] | {r['mean']:+.4f} | {ci(r)} | {'EQUIVALENT' if eq else 'not shown'} | "
                 f"{gains[curve]['mean'] / dec_j:+.1%} |")
    L += ["", "## Practical comparisons (one Holm family of 6)", "",
          "| id | b | design points | ΔJ = JC − b | 95% CI | JC better in | Wilcoxon p | Holm threshold | verdict |",
          "|---|---|---:|---:|---|---:|---:|---:|---|"]
    for hid, (b, r) in tests.items():
        ok = bool(holm[hid]["reject"] and r["ci"][1] < 0)
        L.append(f"| **{hid}** | `{b}` | {r['n']} | {r['mean']:+.4f} | {ci(r)} | {r['better']:.0%} | {r['p']:.3g} | "
                 f"{holm[hid]['threshold']:.4f} | {'PASS' if ok else 'FAIL'} |")
    return "\n".join(L) + "\n"


def main() -> int:
    frames = {c: f for c in CURVES if (f := load(c)) is not None}
    out = record_path(RECORD)
    if len(frames) < len(CURVES):
        out.write_text(f"# Cache sensitivity\n\nNot all campaigns have run: {sorted(frames)}\n", encoding="utf-8")
    else:
        out.write_text(build(frames), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
