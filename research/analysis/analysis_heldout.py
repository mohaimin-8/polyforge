"""PREREG_HELDOUT.md -> RESULTS_HELDOUT.md: the JOINTNESS comparisons on two
workload classes no tuning slice or earlier campaign has seen.

FROZEN with the pre-registration; not edited after the run. The test is the
one PREREG_FAIR_J froze, imported from its scorer (its treatment is this
campaign's); the equivalence reading is PREREG_JOINTNESS's.

    python analysis_heldout.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from analysis_fair_j import (  # noqa: E402
    BOOT_N, BOOT_SEED, DESIGN, NI_MARGIN, TREATMENT, complete_design_points, design_diffs,
    noninferior, score, superiority,
)
from stats import composite_objective, record_path  # noqa: E402

RESULTS = HERE.parents[1] / "eval" / "results"
DB = RESULTS / "raw_sim_heldout.duckdb"
CSV = RESULTS / "metrics_matrix_heldout.csv.gz"
RECORD = "RESULTS_HELDOUT.md"

# One Holm family of 5 (PREREG_HELDOUT, Tests). Ids mirror the JOINTNESS
# hypothesis each replicates.
CONFIRMATORY = {
    "HO-C1": "jcac_decoupled",
    "HO-B1": "layered_small_tuned",
    "HO-B3": "static_share",
    "HO-B4": "hpa_fair_capped",
    "HO-B5": "keda_fair_capped",
}
JOINTNESS_VERDICT = {"HO-C1": "PASS", "HO-B1": "FAIL", "HO-B3": "PASS", "HO-B4": "FAIL",
                     "HO-B5": "PASS"}
EQ_MARGIN = 0.025
FLOOR = "jcac_tier_floor"
ARMS = [TREATMENT, *CONFIRMATORY.values(), FLOOR]
SIZES = ["small", "medium", "large"]
GUARDS = ["tier_none_step_share", "budget_overrun_step_share", "clamp_violation_step_share",
          "plan_fallback_share", "plan_repaired_share"]
BASE_COLUMNS = ["system", "workload", "tenant_mix", "cluster_size", "rep", "total_cost_usd",
                "mean_violation", "mean_jain", "mean_excess"]


def load() -> pd.DataFrame:
    if DB.exists():
        import duckdb

        con = duckdb.connect(str(DB), read_only=True)
        try:
            return con.execute(
                "select r.system, r.workload, r.tenant_mix, r.cluster_size, r.rep, "
                "m.total_cost_usd, m.mean_violation, m.mean_jain, m.mean_excess, "
                + ", ".join(f"m.{g}" for g in GUARDS)
                + " from runs r join metrics m on r.run_id = m.run_id where r.status = 'valid'"
            ).fetchdf()
        finally:
            con.close()
    return pd.read_csv(CSV, float_precision="round_trip")[BASE_COLUMNS + GUARDS]


def prepare(df: pd.DataFrame) -> pd.DataFrame:
    df = complete_design_points(df, ARMS)
    return df.assign(J=composite_objective(df))


def direction(r: dict) -> str:
    if r["ci"][1] < 0:
        return "treatment better"
    if r["ci"][0] > 0:
        return "comparator better"
    return "no difference shown"


def equivalent(r: dict) -> bool:
    return -EQ_MARGIN < r["ci"][0] and r["ci"][1] < EQ_MARGIN


def _ci(r: dict) -> str:
    return f"[{r['ci'][0]:+.4f}, {r['ci'][1]:+.4f}]"


def build(df: pd.DataFrame) -> str:
    n_all = df[DESIGN].drop_duplicates().shape[0]
    df = prepare(df)
    n_dp = df[DESIGN].drop_duplicates().shape[0]
    res = score(df, CONFIRMATORY)
    L = ["# The JOINTNESS comparisons on held-out, non-periodic workloads", "",
         "Generated by `analysis_heldout.py`, frozen with `PREREG_HELDOUT.md`. Treatment "
         f"`{TREATMENT}`; workloads `mmpp_crud` and `mmpp_mixed` (Markov-modulated bursts), "
         f"which no tuning slice or earlier campaign used. Unit: the design point (reps "
         f"averaged); {n_dp} of {n_all} design points complete for every arm (listwise rule). "
         "A PASS needs the one-sided Wilcoxon p at or below its Holm threshold AND the 95% "
         f"bootstrap CI of the mean difference entirely below 0 ({BOOT_N:,} resamples, seed "
         f"{BOOT_SEED}). Negative = the treatment is better.", "",
         "## Per-arm means", "",
         "| arm | J | cost $ | violation | excess | Jain | AI shed | budget overrun | clamp breaks | "
         "fallback plans | repaired plans |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for arm in ARMS:
        s = df[df.system == arm]
        guards = " | ".join("—" if s[g].isna().all() else f"{s[g].mean():.1%}" for g in GUARDS)
        L.append(f"| `{arm}` | {s.J.mean():.4f} | {s.total_cost_usd.mean():.4f} | "
                 f"{s.mean_violation.mean():.4f} | {s.mean_excess.mean():.4f} | {s.mean_jain.mean():.4f} | "
                 f"{guards} |")
    L += ["", "## Confirmatory: HO-C1, HO-B1, HO-B3..B5 (one Holm family of 5)", "",
          "| id | vs | design points | ΔJ | d_z | 95% CI of ΔJ | treatment better in | Wilcoxon p | "
          "Holm threshold | verdict | direction | JOINTNESS verdict |",
          "|---|---|---:|---:|---:|---|---:|---:|---:|---|---|---|"]
    for hid, r in res.items():
        L.append(f"| **{hid}** | `{CONFIRMATORY[hid]}` | {r['n']} | {r['mean']:+.4f} | {r['dz']:+.2f} | "
                 f"{_ci(r)} | {r['better']:.0%} | {r['p']:.3g} | {r['threshold']:.4f} | "
                 f"{'PASS' if r['pass'] else 'FAIL'} | {direction(r)} | {JOINTNESS_VERDICT[hid]} |")
    r = res["HO-C1"]
    L += ["", f"## Coordination: equivalence within ±{EQ_MARGIN} J (registered reading)", "",
          "| id | vs | ΔJ | 95% CI | equivalent? |", "|---|---|---:|---|---|",
          f"| HO-C1-EQ | `jcac_decoupled` | {r['mean']:+.4f} | {_ci(r)} | "
          f"{'EQUIVALENT' if equivalent(r) else 'not shown'} |"]
    L += ["", f"## SLO guard: `mean_excess` non-inferiority (one-sided 95% bootstrap bound < {NI_MARGIN})", "",
          "| guard | vs | mean diff | 95% upper bound | verdict |", "|---|---|---:|---:|---|"]
    for hid, comp in CONFIRMATORY.items():
        g = noninferior(design_diffs(df, TREATMENT, comp, "mean_excess"))
        L.append(f"| {hid}-NI | `{comp}` | {g['mean']:+.4f} | {g['ucb']:+.4f} | {'PASS' if g['ni'] else 'FAIL'} |")
    L += ["", "## Descriptive", "", "| contrast | ΔJ | 95% CI | direction |", "|---|---:|---|---|"]
    rr = superiority(design_diffs(df, FLOOR, TREATMENT, "J"))
    L.append(f"| never shedding: tier floor − treatment | {rr['mean']:+.4f} | {_ci(rr)} | {direction(rr)} |")
    for comp in ("hpa_fair_capped", "layered_small_tuned"):
        rr = superiority(design_diffs(df, FLOOR, comp, "J"))
        L.append(f"| tier floor vs `{comp}` | {rr['mean']:+.4f} | {_ci(rr)} | {direction(rr)} |")
    L += ["", "## Per workload and cluster size (descriptive)", "",
          "| workload | cluster | vs | ΔJ | 95% CI | direction |", "|---|---|---|---:|---|---|"]
    for wl in sorted(df.workload.unique()):
        for size in SIZES:
            sub = df[(df.workload == wl) & (df.cluster_size == size)]
            for comp in CONFIRMATORY.values():
                rr = superiority(design_diffs(sub, TREATMENT, comp, "J"))
                L.append(f"| `{wl}` | {size} | `{comp}` | {rr['mean']:+.4f} | {_ci(rr)} | {direction(rr)} |")
    L.append("")
    return "\n".join(L) + "\n"


def main() -> int:
    out = record_path(RECORD)
    out.write_text(build(load()), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
