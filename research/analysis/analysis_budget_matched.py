"""PREREG_BUDGET_MATCHED.md -> RESULTS_BUDGET_MATCHED.md.

The audited comparators under the joint controller's per-tenant budget
filter, paired with the registered JN and TA runs on identical demand
(shared seeds). FROZEN with the pre-registration; the test rule is
analysis_fair_j's, imported.

    python analysis_budget_matched.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from analysis_fair_j import ALPHA, BOOT_N, BOOT_SEED, DESIGN, boot_means, design_diffs, superiority  # noqa: E402
from stats import holm_bonferroni, record_path  # noqa: E402

RESULTS = HERE.parents[1] / "eval" / "results"
RECORD = "RESULTS_BUDGET_MATCHED.md"
TREATMENT = "jcac_converged"
NEW = ["hpa_budget_capped", "keda_budget_capped", "layered_small_budget"]
TWIN = {"hpa_budget_capped": "hpa_fair_capped", "keda_budget_capped": "keda_fair_capped",
        "layered_small_budget": "layered_small_tuned"}
REGISTERED_ARMS = [TREATMENT, "jcac_tier_floor"] + list(TWIN.values())
TESTS = {"BM-H1": "hpa_budget_capped", "BM-H2": "keda_budget_capped", "BM-H3": "layered_small_budget"}
TENANTS, COST_SCALE_USD = 8, 0.01
KEYS = ["system"] + DESIGN + ["rep", "seed"]
COLUMNS = ["total_cost_usd", "mean_violation", "mean_jain", "mean_excess", "tier_none_step_share",
           "budget_overrun_step_share", "steps"]
# campaign -> (new DB, new export, registered export, expected new runs, reps)
CAMPAIGNS = {
    "JN": ("raw_sim_budget_jointness.duckdb", "metrics_budget_jointness.csv.gz",
           "metrics_matrix_jointness.csv.gz", 900, 5),
    "TA": ("raw_sim_budget_trace.duckdb", "metrics_budget_trace.csv.gz", "metrics_trace_audited.csv.gz", 288, 1),
}


def load_new(campaign: str) -> pd.DataFrame | None:
    db, export, _, _, _ = CAMPAIGNS[campaign]
    if (RESULTS / db).exists():
        import duckdb

        con = duckdb.connect(str(RESULTS / db), read_only=True)
        try:
            return con.execute(
                "select " + ", ".join(f"r.{c}" for c in KEYS) + ", " + ", ".join(f"m.{c}" for c in COLUMNS)
                + " from runs r join metrics m on r.run_id = m.run_id where r.status = 'valid'").fetchdf()
        finally:
            con.close()
    if (RESULTS / export).exists():
        return pd.read_csv(RESULTS / export, float_precision="round_trip")[KEYS + COLUMNS]
    return None


def load_registered(campaign: str) -> pd.DataFrame:
    ref = pd.read_csv(RESULTS / CAMPAIGNS[campaign][2], float_precision="round_trip")
    return ref[ref.system.isin(REGISTERED_ARMS)][KEYS + COLUMNS]


def seeds_match(new: pd.DataFrame, ref: pd.DataFrame) -> tuple[bool, str]:
    """BM-V: each new run's seed is the registered seed of its design point and rep."""
    registered = ref[ref.system == TREATMENT].set_index(DESIGN + ["rep"]).seed
    got = new.set_index(DESIGN + ["rep"]).seed
    want = registered.reindex(got.index)
    bad = int((want.isna() | (got != want)).sum())
    return bad == 0, f"{len(new):,} new runs; seeds differing from the registered design point: {bad}"


def complete(df: pd.DataFrame, arms: list[str], reps: int) -> pd.DataFrame:
    counts = df[df.system.isin(arms)].groupby(DESIGN + ["system"]).size().unstack("system")
    ok = counts.reindex(columns=arms).fillna(0).ge(reps).all(axis=1)
    keep = set(counts.index[ok])
    return df[[k in keep for k in zip(*(df[c] for c in DESIGN))]]


def score_j(df: pd.DataFrame) -> pd.Series:
    return (df.total_cost_usd / (df.steps * TENANTS) / COST_SCALE_USD
            + 2.0 * df.mean_violation + 0.5 * (1.0 - df.mean_jain))


def ci(lo: float, hi: float) -> str:
    return f"[{lo:+.4f}, {hi:+.4f}]"


def effect(df: pd.DataFrame, a: str, b: str, metric: str) -> tuple[float, float, float]:
    d = design_diffs(df, a, b, metric)
    means = boot_means(d)
    return float(d.mean()), float(np.percentile(means, 2.5)), float(np.percentile(means, 97.5))


def build(frames: dict[str, tuple[pd.DataFrame, bool, str]]) -> str:
    L = ["# The audited comparators under the joint controller's budget", "",
         "Generated by `analysis_budget_matched.py`, frozen with `PREREG_BUDGET_MATCHED.md`. The budget-matched "
         "arms ran under the registered experiment names, so they share the registered runs' seeds and demand; "
         "the treatment, the never-shedding arm and the unbudgeted twins are the registered rows. Unit: the design "
         "point (JN, reps averaged) or the window (TA), listwise complete. J uses each run's own scored steps. "
         f"PASS = one-sided Wilcoxon at its Holm threshold AND the 95% bootstrap CI below 0 ({BOOT_N:,} resamples, "
         f"seed {BOOT_SEED}). Negative ΔJ = JC better.", ""]
    tests, voided = {}, []
    prepared = {}
    for campaign, (df, ok, gate_line) in frames.items():
        L += [f"## {campaign}", "", f"**BM-V (shared seeds): {'HOLDS' if ok else 'FAILS'}** — {gate_line}", ""]
        if not ok:
            voided.append(campaign)
            L += ["The new arms did not see the registered demand: this campaign's tests are void.", ""]
            continue
        reps = CAMPAIGNS[campaign][4]
        n_all = df[DESIGN].drop_duplicates().shape[0]
        df = complete(df, REGISTERED_ARMS + NEW, reps)
        df = df.assign(J=score_j(df))
        prepared[campaign] = df
        n = df[DESIGN].drop_duplicates().shape[0]
        L += [f"{n} of {n_all} units complete.", "",
              "| arm | J | cost $ | violation | excess | Jain | budget overrun | AI shed |",
              "|---|---:|---:|---:|---:|---:|---:|---:|"]
        for arm in REGISTERED_ARMS[:2] + [x for pair in TWIN.items() for x in pair[::-1]]:
            s = df[df.system == arm]
            L.append(f"| `{arm}` | {s.J.mean():.4f} | {s.total_cost_usd.mean():.3f} | {s.mean_violation.mean():.4f} | "
                     f"{s.mean_excess.mean():.4f} | {s.mean_jain.mean():.4f} | "
                     f"{s.budget_overrun_step_share.mean():.1%} | {s.tier_none_step_share.mean():.1%} |")
        L += ["", "Effect of the budget filter on each comparator (budgeted − unbudgeted, 95% bootstrap CI):", "",
              "| comparator | ΔJ | Δcost $ | Δviolation | Δoverrun share |", "|---|---|---|---|---|"]
        for arm, twin in TWIN.items():
            cells = [effect(df, arm, twin, m) for m in ("J", "total_cost_usd", "mean_violation",
                                                         "budget_overrun_step_share")]
            L.append(f"| `{twin}` | " + " | ".join(f"{m:+.4f} {ci(lo, hi)}" for m, lo, hi in cells) + " |")
        L.append("")
        for hid, b in TESTS.items():
            tests[f"{hid}[{campaign}]"] = (b, superiority(design_diffs(df, TREATMENT, b, "J")))
    holm = holm_bonferroni({hid: r["p"] for hid, (_, r) in tests.items()}, ALPHA) if tests else {}
    L += ["## Confirmatory: BM-H1..H3 on JN and TA (one Holm family of 6)", "",
          "| id | b | units | ΔJ = JC − b | 95% CI | JC better in | Wilcoxon p | Holm threshold | verdict |",
          "|---|---|---:|---:|---|---:|---:|---:|---|"]
    for hid, (b, r) in tests.items():
        ok = bool(holm[hid]["reject"] and r["ci"][1] < 0)
        L.append(f"| **{hid}** | `{b}` | {r['n']} | {r['mean']:+.4f} | {ci(*r['ci'])} | {r['better']:.0%} | "
                 f"{r['p']:.3g} | {holm[hid]['threshold']:.4f} | {'PASS' if ok else 'FAIL'} |")
    for campaign in voided:
        L.append(f"| BM-H1..H3[{campaign}] | — | — | — | — | — | — | — | VOID (BM-V) |")
    return "\n".join(L) + "\n"


def main() -> int:
    frames = {}
    for campaign in CAMPAIGNS:
        new = load_new(campaign)
        if new is None:
            continue
        ref = load_registered(campaign)
        ok, line = seeds_match(new, ref)
        expected = CAMPAIGNS[campaign][3]
        if len(new) != expected:
            ok, line = False, line + f"; runs {len(new)} != expected {expected}"
        frames[campaign] = (pd.concat([ref, new], ignore_index=True), ok, line)
    out = record_path(RECORD)
    if len(frames) < len(CAMPAIGNS):
        out.write_text(f"# Budget-matched comparators\n\nNot all campaigns have run: {sorted(frames)}\n",
                       encoding="utf-8")
    else:
        out.write_text(build(frames), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
