"""PREREG_LEVEL2.md -> RESULTS_LEVEL2.md.

The best joint controller found (jcac_level_ratchet, LEVEL_LAG) re-tested on
fresh seeds against every LEVEL comparator on every LEVEL substrate, plus the
main matrix under the measured GPU price ladder with cost-aware comparators.
FROZEN with the pre-registration. J_L, loaders and the superiority rule are
analysis_level's (FAIR_J rule), imported unchanged.

    python analysis_level2.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from analysis_fair_j import ALPHA, BOOT_N, BOOT_SEED, DESIGN, NI_MARGIN, boot_means, design_diffs, superiority  # noqa: E402
from analysis_level import ci, complete, effect, load, prepare  # noqa: E402
from stats import holm_bonferroni, record_path  # noqa: E402

RECORD = "RESULTS_LEVEL2.md"
TREATMENT, DECOUPLED = "jcac_level_ratchet", "jcac_level_ratchet_decoupled"
GATED, CAPPED, HPA, KEDA, STATIC = ("layered_small_level_gated", "layered_small_level_capped",
                                    "hpa_level_capped", "keda_level_capped", "static_share")
CA_GATED, CA_CAPPED, SM_GPU, HPA_GPU = ("layered_costaware_gpu_gated", "layered_costaware_gpu_capped",
                                        "layered_small_gpu_gated", "hpa_gpu_capped")
MAIN_ARMS = [TREATMENT, DECOUPLED, GATED, CAPPED, HPA, KEDA, STATIC]
GPU_ARMS = [TREATMENT, DECOUPLED, CA_GATED, CA_CAPPED, SM_GPU, HPA_GPU, STATIC]
# key -> (experiment, arms, reps, expected valid runs, label)
CAMPAIGNS = {
    "M": ("matrix_level2", MAIN_ARMS, 5, 2100, "main matrix, published plant"),
    "R": ("matrix_level2_mono", MAIN_ARMS, 5, 2100, "main matrix, monotone agent row"),
    "L": ("matrix_level2_lag", MAIN_ARMS, 5, 2100, "main matrix, replicas one interval late"),
    "O": ("matrix_level2_heldout", MAIN_ARMS, 5, 840, "held-out MMPP workloads"),
    "T": ("matrix_level2_trace", MAIN_ARMS, 1, 672, "real BurstGPT windows"),
    "G": ("matrix_level2_gpu", GPU_ARMS, 5, 2100, "main matrix, measured GPU price ladder"),
}
TESTS = {
    "L2-M1": ("M", GATED), "L2-M2": ("M", CAPPED), "L2-M3": ("M", HPA), "L2-M4": ("M", KEDA), "L2-M5": ("M", STATIC),
    "L2-R1": ("R", GATED), "L2-R2": ("R", CAPPED),
    "L2-L1": ("L", CAPPED), "L2-L2": ("L", HPA), "L2-L3": ("L", KEDA),
    "L2-O1": ("O", GATED), "L2-O2": ("O", CAPPED), "L2-O3": ("O", HPA),
    "L2-T1": ("T", GATED), "L2-T2": ("T", CAPPED), "L2-T3": ("T", HPA),
    "L2-G1": ("G", CA_GATED), "L2-G2": ("G", CA_CAPPED), "L2-G3": ("G", HPA_GPU),
}
EQ_MARGIN = 0.01


def build(frames: dict[str, tuple[pd.DataFrame, str]]) -> str:
    L = ["# LEVEL2: the best joint controller found, re-tested against every level comparator", "",
         "Generated by `analysis_level2.py`, frozen with `PREREG_LEVEL2.md`. Treatment `jcac_level_ratchet`. "
         "Objective J_L (LEVEL's). PASS = one-sided Wilcoxon at its Holm threshold (one family of "
         f"{len(TESTS)}) AND the 95% bootstrap CI of the mean ΔJ_L below 0 ({BOOT_N:,} resamples, seed "
         f"{BOOT_SEED}). Unit: the design point (reps averaged) or the window. Negative = treatment better.", ""]
    prepared = {}
    for key, (df, line) in frames.items():
        experiment, arms, reps, _, label = CAMPAIGNS[key]
        n_all = df[DESIGN].drop_duplicates().shape[0]
        df = prepare(complete(df, arms, reps))
        prepared[key] = df
        n = df[DESIGN].drop_duplicates().shape[0]
        L += [f"## {key}: {label} (`{experiment}`)", "", f"Validity: {line}; {n} of {n_all} units complete.", "",
              "| arm | J_L | J | cost $ | violation | excess | Jain | shed (requests) | budget overrun |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for arm in arms:
            s = df[df.system == arm]
            L.append(f"| `{arm}` | {s.J_L.mean():.4f} | {s.J.mean():.4f} | {s.total_cost_usd.mean():.3f} | "
                     f"{s.mean_violation.mean():.4f} | {s.mean_excess.mean():.4f} | {s.mean_jain.mean():.4f} | "
                     f"{s.shed_request_share.mean():.1%} | {s.budget_overrun_step_share.mean():.1%} |")
        L.append("")
    results = {hid: (key, comp, superiority(design_diffs(prepared[key], TREATMENT, comp, "J_L")))
               for hid, (key, comp) in TESTS.items() if key in prepared}
    holm = holm_bonferroni({hid: r["p"] for hid, (_, _, r) in results.items()}, ALPHA) if results else {}
    L += [f"## Confirmatory (one Holm family of {len(TESTS)})", "",
          "| id | campaign | vs | units | ΔJ_L | d_z | 95% CI | treatment better in | Wilcoxon p | Holm threshold | verdict |",
          "|---|---|---|---:|---:|---:|---|---:|---:|---:|---|"]
    for hid, (key, comp, r) in results.items():
        ok = bool(holm[hid]["reject"] and r["ci"][1] < 0)
        L.append(f"| **{hid}** | {key} | `{comp}` | {r['n']} | {r['mean']:+.4f} | {r['dz']:+.2f} | {ci(*r['ci'])} | "
                 f"{r['better']:.0%} | {r['p']:.3g} | {holm[hid]['threshold']:.4f} | {'PASS' if ok else 'FAIL'} |")
    for hid, (key, comp) in TESTS.items():
        if hid not in results:
            L.append(f"| {hid} | {key} | `{comp}` | — | — | — | — | — | — | — | NOT RUN |")
    L += ["", f"## Coordination: treatment − decoupled search on J_L (registered margin ±{EQ_MARGIN})", "",
          "| id | ΔJ_L | 95% CI | gain, % of decoupled J_L | equivalent |", "|---|---:|---|---:|---|"]
    for key, df in prepared.items():
        m, lo, hi = effect(df, TREATMENT, DECOUPLED, "J_L")
        base = df[df.system == DECOUPLED].J_L.mean()
        L.append(f"| L2-C[{key}] | {m:+.4f} | {ci(lo, hi)} | {-100 * m / base:+.1f}% | "
                 f"{'EQUIVALENT' if -EQ_MARGIN < lo and hi < EQ_MARGIN else 'not shown'} |")
    for key, df in prepared.items():
        comps = [c for (k, c) in TESTS.values() if k == key]
        L += ["", f"## Per metric, treatment − comparator ({key}; descriptive)", "",
              "| vs | ΔJ (published) | Δcost $ | Δviolation | Δexcess | Δshed requests | "
              f"excess non-inferior (+{NI_MARGIN})? |", "|---|---|---|---|---|---|---|"]
        for comp in comps:
            cells = [effect(df, TREATMENT, comp, x) for x in
                     ("J", "total_cost_usd", "mean_violation", "mean_excess", "shed_request_share")]
            ucb = float(np.percentile(boot_means(design_diffs(df, TREATMENT, comp, "mean_excess")), 95.0))
            L.append(f"| `{comp}` | " + " | ".join(f"{a:+.4f} {ci(b, c)}" for a, b, c in cells)
                     + f" | {'PASS' if ucb < NI_MARGIN else 'FAIL'} (UB {ucb:+.4f}) |")
    for key in ("M", "G"):
        if key not in prepared:
            continue
        df = prepared[key]
        comps = [c for (k, c) in TESTS.values() if k == key][:3]
        L += ["", f"## Per cluster size and workload, treatment − comparator on J_L ({key}; descriptive)", "",
              "| cut | vs | units | ΔJ_L | 95% CI |", "|---|---|---:|---:|---|"]
        cuts = [("size=" + s, df[df.cluster_size == s]) for s in ("small", "medium", "large")]
        cuts += [("workload=" + w, df[df.workload == w]) for w in sorted(df.workload.unique())]
        for name, sub in cuts:
            for comp in comps:
                a, b, c = effect(sub, TREATMENT, comp, "J_L")
                L.append(f"| {name} | `{comp}` | {sub[DESIGN].drop_duplicates().shape[0]} | {a:+.4f} | {ci(b, c)} |")
    return "\n".join(L) + "\n"


def main() -> int:
    frames = {}
    for key, (experiment, arms, _, expected, _) in CAMPAIGNS.items():
        df = load(experiment)
        if df is None:
            continue
        frames[key] = (df, f"{len(df[df.system.isin(arms)]):,} valid runs of {expected:,} expected")
    out = record_path(RECORD)
    out.write_text(build(frames) if frames else "# LEVEL2\n\nNo campaign has run.\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
