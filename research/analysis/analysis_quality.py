"""PREREG_QUALITY.md -> RESULTS_QUALITY.md: joint control when the tier knob
trades answer quality.

FROZEN with the pre-registration; not edited after the run. The test is the
PREREG_FAIR_J rule -- the design point as the unit, a one-sided Wilcoxon at
its Holm threshold AND a 95% bootstrap CI below 0 -- built from the frozen
scorer's own functions; only the objective (J priced with the answer-quality
loss) and the treatment differ, so the rule is applied here rather than
called through `analysis_fair_j.score`, which hard-codes FAIR_J's treatment.

    python analysis_quality.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from analysis_fair_j import (  # noqa: E402
    ALPHA, BOOT_N, BOOT_SEED, DESIGN, NI_MARGIN, complete_design_points, design_diffs,
    noninferior, superiority,
)
from stats import composite_objective, holm_bonferroni, record_path  # noqa: E402

RESULTS = HERE.parents[1] / "eval" / "results"
DB = RESULTS / "raw_sim_quality.duckdb"
CSV = RESULTS / "metrics_matrix_quality.csv.gz"
RECORD = "RESULTS_QUALITY.md"

TREATMENT = "jcac_quality"
QUALITY_WEIGHT = 2.0       # registered: the controller's and the scorer's
EQ_MARGIN = 0.025          # registered equivalence margin on design-point mean ΔJ_q
CONFIRMATORY = {           # one Holm family of 5
    "QL-C1": "jcac_quality_decoupled",
    "QL-C2": "jcac_quality_knobwise",
    "QL-B1": "layered_quality_capped",
    "QL-B2": "hpa_quality_capped",
    "QL-B3": "static_share_quality",
}
COORDINATION = ("QL-C1", "QL-C2")
BUDGETED = "jcac_quality_budget"
BLIND = "jcac_converged"
ARMS = [TREATMENT, *CONFIRMATORY.values(), BUDGETED, BLIND]
SIZES = ["small", "medium", "large"]
AI_WORKLOADS = ["ai_cacheable", "ai_uncacheable", "agentic"]
METRICS = [("total_cost_usd", "cost $"), ("mean_violation", "violation"),
           ("mean_excess", "excess"), ("mean_quality_loss", "quality loss"), ("mean_jain", "Jain")]
GUARDS = ["tier_none_step_share", "budget_overrun_step_share", "plan_fallback_share",
          "plan_repaired_share"]
BASE_COLUMNS = ["system", "workload", "tenant_mix", "cluster_size", "rep", "total_cost_usd",
                "mean_violation", "mean_jain", "mean_excess", "mean_quality_loss"]


def load() -> pd.DataFrame:
    if DB.exists():
        import duckdb

        con = duckdb.connect(str(DB), read_only=True)
        try:
            return con.execute(
                "select r.system, r.workload, r.tenant_mix, r.cluster_size, r.rep, "
                "m.total_cost_usd, m.mean_violation, m.mean_jain, m.mean_excess, "
                "m.mean_quality_loss, " + ", ".join(f"m.{g}" for g in GUARDS)
                + " from runs r join metrics m on r.run_id = m.run_id where r.status = 'valid'"
            ).fetchdf()
        finally:
            con.close()
    return pd.read_csv(CSV, float_precision="round_trip")[BASE_COLUMNS + GUARDS]


def quality_j(df: pd.DataFrame) -> pd.Series:
    """J_q: the paper's composite objective plus the priced quality loss."""
    return composite_objective(df) + QUALITY_WEIGHT * df.mean_quality_loss


def prepare(df: pd.DataFrame) -> pd.DataFrame:
    df = complete_design_points(df, ARMS)
    return df.assign(J=quality_j(df))


def score(df: pd.DataFrame) -> dict[str, dict]:
    """The FAIR_J rule with this campaign's treatment."""
    res = {hid: superiority(design_diffs(df, TREATMENT, comp, "J")) for hid, comp in CONFIRMATORY.items()}
    holm = holm_bonferroni({hid: r["p"] for hid, r in res.items()}, ALPHA)
    for hid, r in res.items():
        r["threshold"] = holm[hid]["threshold"]
        r["pass"] = bool(holm[hid]["reject"] and r["ci"][1] < 0)
    return res


def direction(r: dict) -> str:
    if r["ci"][1] < 0:
        return "treatment better"
    if r["ci"][0] > 0:
        return "comparator better"
    return "no difference shown"


def equivalent(r: dict) -> bool:
    return -EQ_MARGIN < r["ci"][0] and r["ci"][1] < EQ_MARGIN


def _ci(r: dict) -> str:
    return f"[{r['ci'][0]:+.4f}, {r['ci'][1]:+.4f}]"


def build(df: pd.DataFrame) -> str:
    n_all = df[DESIGN].drop_duplicates().shape[0]
    df = prepare(df)
    n_dp = df[DESIGN].drop_duplicates().shape[0]
    res = score(df)
    L = ["# Joint control when the tier knob trades answer quality", "",
         "Generated by `analysis_quality.py`, frozen with `PREREG_QUALITY.md`. Treatment "
         f"`{TREATMENT}`. J_q = J + {QUALITY_WEIGHT} x answer-quality loss (`model.TIER_QUALITY`, "
         "cache hits at the measured relative precision), under the measured GPU price ladder. "
         f"Unit: the design point (reps averaged); {n_dp} of {n_all} design points complete for "
         "every arm (listwise rule). A PASS needs the one-sided Wilcoxon p at or below its Holm "
         f"threshold AND the 95% bootstrap CI of the mean ΔJ_q entirely below 0 ({BOOT_N:,} "
         f"resamples, seed {BOOT_SEED}). Negative = the treatment is better.", "",
         "## Per-arm means", "",
         "| arm | J_q | J | cost $ | violation | excess | quality loss | Jain | AI shed | "
         "budget overrun | fallback plans | repaired plans |",
         "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for arm in ARMS:
        s = df[df.system == arm]
        guards = " | ".join("—" if s[g].isna().all() else f"{s[g].mean():.1%}" for g in GUARDS)
        L.append(f"| `{arm}` | {s.J.mean():.4f} | {composite_objective(s).mean():.4f} | "
                 f"{s.total_cost_usd.mean():.4f} | {s.mean_violation.mean():.4f} | "
                 f"{s.mean_excess.mean():.4f} | {s.mean_quality_loss.mean():.4f} | "
                 f"{s.mean_jain.mean():.4f} | {guards} |")
    L += ["", "## Confirmatory: QL-C1, QL-C2, QL-B1..B3 (one Holm family of 5)", "",
          "| id | vs | design points | ΔJ_q | d_z | 95% CI | treatment better in | Wilcoxon p | "
          "Holm threshold | verdict | direction |", "|---|---|---:|---:|---:|---|---:|---:|---:|---|---|"]
    for hid, r in res.items():
        L.append(f"| **{hid}** | `{CONFIRMATORY[hid]}` | {r['n']} | {r['mean']:+.4f} | {r['dz']:+.2f} | "
                 f"{_ci(r)} | {r['better']:.0%} | {r['p']:.3g} | {r['threshold']:.4f} | "
                 f"{'PASS' if r['pass'] else 'FAIL'} | {direction(r)} |")
    L += ["", f"## Coordination: equivalence within ±{EQ_MARGIN} J_q (registered reading)", "",
          "| id | vs | ΔJ_q | 95% CI | equivalent? |", "|---|---|---:|---|---|"]
    for hid in COORDINATION:
        r = res[hid]
        L.append(f"| {hid}-EQ | `{CONFIRMATORY[hid]}` | {r['mean']:+.4f} | {_ci(r)} | "
                 f"{'EQUIVALENT' if equivalent(r) else 'not shown'} |")
    L += ["", f"## SLO guard: `mean_excess` non-inferiority (one-sided 95% bootstrap bound < {NI_MARGIN})", "",
          "| guard | vs | mean diff | 95% upper bound | verdict |", "|---|---|---:|---:|---|"]
    for hid, comp in CONFIRMATORY.items():
        g = noninferior(design_diffs(df, TREATMENT, comp, "mean_excess"))
        L.append(f"| {hid}-NI | `{comp}` | {g['mean']:+.4f} | {g['ucb']:+.4f} | {'PASS' if g['ni'] else 'FAIL'} |")
    L += ["", "## Per metric, treatment vs each arm (descriptive)", "",
          "| vs | " + " | ".join(f"Δ{n} [95% CI]" for _, n in METRICS) + " |", "|---|" + "---|" * len(METRICS)]
    for comp in [*CONFIRMATORY.values(), BUDGETED, BLIND]:
        cells = []
        for metric, _ in METRICS:
            r = superiority(design_diffs(df, TREATMENT, comp, metric))
            cells.append(f"{r['mean']:+.4f} {_ci(r)}")
        L.append(f"| `{comp}` | " + " | ".join(cells) + " |")
    L += ["", "## What the budget filter and ignoring quality cost (descriptive)", "",
          "| contrast | ΔJ_q | 95% CI | reading |", "|---|---:|---|---|"]
    for label, arm in (("with the per-tenant budget filter", BUDGETED),
                       ("quality-blind published treatment", BLIND)):
        r = superiority(design_diffs(df, arm, TREATMENT, "J"))
        reading = ("this arm better" if r["ci"][1] < 0 else "treatment better" if r["ci"][0] > 0
                   else "no difference shown")
        L.append(f"| `{arm}` ({label}) − treatment | {r['mean']:+.4f} | {_ci(r)} | {reading} |")
    L += ["", "## Per cluster size (descriptive)", "", "| cluster | vs | ΔJ_q | 95% CI | direction |",
          "|---|---|---:|---|---|"]
    for size in SIZES:
        sub = df[df.cluster_size == size]
        for comp in CONFIRMATORY.values():
            rr = superiority(design_diffs(sub, TREATMENT, comp, "J"))
            L.append(f"| {size} | `{comp}` | {rr['mean']:+.4f} | {_ci(rr)} | {direction(rr)} |")
    L += ["", "## Per workload (descriptive)", "", "| workload | vs | ΔJ_q | treatment better in |",
          "|---|---|---:|---:|"]
    for comp in CONFIRMATORY.values():
        ma = df[df.system == TREATMENT].groupby(DESIGN).J.mean()
        mb = df[df.system == comp].groupby(DESIGN).J.mean()
        d = (ma - mb).dropna()
        for wl, sub in d.groupby(level="workload"):
            L.append(f"| `{wl}` | `{comp}` | {sub.mean():+.4f} | {int((sub < 0).sum())}/{len(sub)} |")
    ai = df[df.workload.isin(AI_WORKLOADS)]
    L += ["", "## AI workloads only (descriptive)", "", "| vs | design points | ΔJ_q | 95% CI | direction |",
          "|---|---:|---:|---|---|"]
    for comp in CONFIRMATORY.values():
        rr = superiority(design_diffs(ai, TREATMENT, comp, "J"))
        L.append(f"| `{comp}` | {rr['n']} | {rr['mean']:+.4f} | {_ci(rr)} | {direction(rr)} |")
    L.append("")
    return "\n".join(L) + "\n"


def main() -> int:
    out = record_path(RECORD)
    out.write_text(build(load()), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
