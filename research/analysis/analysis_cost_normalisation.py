"""Exploratory check -> COST_NORMALISATION.md.

The composite objective divides a run's cost by 119 x 8 tenant-steps
(`stats.composite_objective`, kept from an earlier harness in which a 120-step
run scored 119 steps). The simulator now scores every one of a run's 120
steps (`simulate.run` scores each plan against the next of steps + 1
buckets), so J's cost term is 960/952 = 1.0084 times the cost per scored
tenant-step. Registered verdicts stand as scored; this re-scores every
registered test of the campaigns the paper reports with the 120-step
normalisation and lists any verdict that changes. Nothing frozen is edited:
the re-scored records are written to a temporary directory.

    python analysis_cost_normalisation.py
"""

from __future__ import annotations

import importlib
import os
import re
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import stats  # noqa: E402

RECORD = "COST_NORMALISATION.md"
SCORED_STEPS, TENANTS, COST_SCALE_USD = 120, 8, 0.01
SCORERS = {
    "analysis_fair_j": "RESULTS_FAIR_J.md",
    "analysis_retuned": "RESULTS_RETUNED.md",
    "analysis_jointness": "RESULTS_JOINTNESS.md",
    "analysis_actuation": "RESULTS_ACTUATION.md",
    "analysis_quality": "RESULTS_QUALITY.md",
    "analysis_heldout": "RESULTS_HELDOUT.md",
    "analysis_width": "RESULTS_WIDTH.md",
    "analysis_reviewer": "RESULTS_REVIEWER_FOLLOWUP.md",
}
VERDICT = re.compile(r"\b(PASS|FAIL|EQUIVALENT|not shown|VACUOUS)\b")
ROW_ID = re.compile(r"^\|\s*\**([A-Z]{2}-[A-Za-z0-9\-\[\]\.]+)\**\s*\|")


def composite_scored_steps(df):
    return (df.total_cost_usd / (SCORED_STEPS * TENANTS) / COST_SCALE_USD
            + 2.0 * df.mean_violation + 0.5 * (1.0 - df.mean_jain))


def rows(text: str) -> dict[str, tuple[str, str]]:
    out = {}
    for line in text.splitlines():
        m = ROW_ID.match(line)
        if m:
            v = VERDICT.findall(line)
            if v:
                out.setdefault(m.group(1), (v[-1], line))
    return out


def main() -> int:
    out_path = stats.record_path(RECORD)
    scratch = tempfile.mkdtemp(prefix="cost_norm_")
    os.environ["POLYFORGE_ANALYSIS_OUT"] = scratch
    stats.composite_objective = composite_scored_steps  # scorers import it by name below
    summary, changed = [], []
    for module, record in SCORERS.items():
        importlib.import_module(module).main()
        old = rows((HERE / record).read_text(encoding="utf-8"))
        new = rows((Path(scratch) / record).read_text(encoding="utf-8"))
        diff = [(hid, old[hid], new.get(hid)) for hid in old if new.get(hid, ("",))[0] != old[hid][0]]
        summary.append((record, len(old), len(diff)))
        changed += [(record, *d) for d in diff]
    total = sum(n for _, n, _ in summary)
    L = ["# Cost normalisation: 119 or 120 scored steps (exploratory check)", "",
         "Generated by `analysis_cost_normalisation.py`. **Exploratory; changes no registered verdict.** "
         "The composite objective divides a run's cost by 119 x 8 tenant-steps; the simulator scores 120 "
         "steps per run, so J's cost term is 960/952 = 1.0084 times the cost per scored tenant-step. Every "
         "registered test of the records below is re-scored with the 120-step normalisation. "
         "`RESULTS_TRACE_AUDITED.md` already divides by each run's own scored steps and is not affected.", "",
         "| record | registered verdict rows | changed |", "|---|---:|---:|"]
    L += [f"| `{r}` | {n} | {c} |" for r, n, c in summary]
    L += [f"| **total** | **{total}** | **{len(changed)}** |", ""]
    if changed:
        L += ["## Verdicts that change", "", "| record | test | registered | with 120 steps |", "|---|---|---|---|"]
        L += [f"| `{r}` | {hid} | {o[0]} | {n[0] if n else 'missing'} |" for r, hid, o, n in changed]
        L += ["", "Rows as printed (registered, then re-scored):", ""]
        for _, _, o, n in changed:
            L += ["    " + o[1], "    " + (n[1] if n else "missing")]
        L.append("")
    out_path.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
