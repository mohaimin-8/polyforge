"""PREREG_LEVEL_LAG.md -> RESULTS_LEVEL_LAG.md.

One changed factor after LEVEL's lag failure: jcac_level with the published
switching penalty (jcac_level_ratchet) against jcac_level and LEVEL's two
strongest comparators, with replicas one interval late (primary) and with
instant actuation (control). FROZEN with the pre-registration. Objective,
loaders and the superiority rule are analysis_level's (J_L, FAIR_J rule),
imported unchanged.

    python analysis_level_lag.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from analysis_fair_j import ALPHA, BOOT_N, BOOT_SEED, DESIGN, design_diffs, superiority  # noqa: E402
from analysis_level import ci, complete, effect, load, prepare  # noqa: E402
from stats import holm_bonferroni, record_path  # noqa: E402

RECORD = "RESULTS_LEVEL_LAG.md"
TREATMENT = "jcac_level_ratchet"
ARMS = [TREATMENT, "jcac_level", "layered_small_level_gated", "hpa_level_capped"]
CAMPAIGNS = {"LAG": ("matrix_level_lag2", 1200), "INST": ("matrix_level_inst2", 1200)}
REPS = 5
TESTS = {
    "LL-H1": ("LAG", "jcac_level"),
    "LL-H2": ("LAG", "layered_small_level_gated"),
    "LL-H3": ("LAG", "hpa_level_capped"),
    "LL-H4": ("INST", "jcac_level"),
    "LL-H5": ("INST", "layered_small_level_gated"),
}


def build(frames: dict[str, tuple[pd.DataFrame, str]]) -> str:
    L = ["# LEVEL_LAG: does the published hysteresis fix the corrected controller's loss under actuation lag?", "",
         "Generated by `analysis_level_lag.py`, frozen with `PREREG_LEVEL_LAG.md`. Treatment `jcac_level_ratchet` "
         "(jcac_level with the published switching penalty). Objective J_L and the FAIR_J rule as in LEVEL: PASS = "
         f"one-sided Wilcoxon at its Holm threshold (one family of {len(TESTS)}) AND the 95% bootstrap CI of the mean "
         f"design-point ΔJ_L below 0 ({BOOT_N:,} resamples, seed {BOOT_SEED}). Negative = treatment better.", ""]
    prepared = {}
    for key, (df, line) in frames.items():
        n_all = df[DESIGN].drop_duplicates().shape[0]
        df = prepare(complete(df, ARMS, REPS))
        prepared[key] = df
        n = df[DESIGN].drop_duplicates().shape[0]
        L += [f"## {key} (`{CAMPAIGNS[key][0]}`)", "", f"Validity: {line}; {n} of {n_all} design points complete.", "",
              "| arm | J_L | J | cost $ | violation | excess | Jain | shed (requests) | budget overrun |",
              "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
        for arm in ARMS:
            s = df[df.system == arm]
            L.append(f"| `{arm}` | {s.J_L.mean():.4f} | {s.J.mean():.4f} | {s.total_cost_usd.mean():.3f} | "
                     f"{s.mean_violation.mean():.4f} | {s.mean_excess.mean():.4f} | {s.mean_jain.mean():.4f} | "
                     f"{s.shed_request_share.mean():.1%} | {s.budget_overrun_step_share.mean():.1%} |")
        L.append("")
    results = {hid: (key, comp, superiority(design_diffs(prepared[key], TREATMENT, comp, "J_L")))
               for hid, (key, comp) in TESTS.items() if key in prepared}
    holm = holm_bonferroni({hid: r["p"] for hid, (_, _, r) in results.items()}, ALPHA) if results else {}
    L += [f"## Confirmatory: LL-H1..H5 (one Holm family of {len(TESTS)})", "",
          "| id | campaign | vs | design points | ΔJ_L | d_z | 95% CI | treatment better in | Wilcoxon p | Holm threshold | verdict |",
          "|---|---|---|---:|---:|---:|---|---:|---:|---:|---|"]
    for hid, (key, comp, r) in results.items():
        ok = bool(holm[hid]["reject"] and r["ci"][1] < 0)
        L.append(f"| **{hid}** | {key} | `{comp}` | {r['n']} | {r['mean']:+.4f} | {r['dz']:+.2f} | {ci(*r['ci'])} | "
                 f"{r['better']:.0%} | {r['p']:.3g} | {holm[hid]['threshold']:.4f} | {'PASS' if ok else 'FAIL'} |")
    for key, df in prepared.items():
        L += ["", f"## Per metric, treatment − each arm ({key}; descriptive)", "",
              "| vs | ΔJ (published) | Δcost $ | Δviolation | Δexcess | Δshed requests |", "|---|---|---|---|---|---|"]
        for comp in ARMS[1:]:
            cells = [effect(df, TREATMENT, comp, m) for m in
                     ("J", "total_cost_usd", "mean_violation", "mean_excess", "shed_request_share")]
            L.append(f"| `{comp}` | " + " | ".join(f"{m:+.4f} {ci(lo, hi)}" for m, lo, hi in cells) + " |")
    return "\n".join(L) + "\n"


def main() -> int:
    frames = {}
    for key, (experiment, expected) in CAMPAIGNS.items():
        df = load(experiment)
        if df is None:
            continue
        valid = len(df[df.system.isin(ARMS)])
        frames[key] = (df, f"{valid:,} valid runs of {expected:,} expected")
    out = record_path(RECORD)
    out.write_text(build(frames) if frames else "# LEVEL_LAG\n\nNo campaign has run.\n", encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
