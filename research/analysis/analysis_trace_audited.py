"""PREREG_TRACE_AUDITED.md -> RESULTS_TRACE_AUDITED.md.

Real BurstGPT demand (the 96 TRACE2 windows) against the audited comparators.
FROZEN with the pre-registration; the test rule is analysis_fair_j's, imported.
J uses each run's own scored steps: the matrix's `composite_objective`
assumes 119.

    python analysis_trace_audited.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from analysis_fair_j import ALPHA, BOOT_N, BOOT_SEED, DESIGN, design_diffs, superiority  # noqa: E402
from stats import holm_bonferroni, record_path  # noqa: E402

RESULTS = HERE.parents[1] / "eval" / "results"
DB = RESULTS / "raw_sim_trace_audited.duckdb"
EXPORT = RESULTS / "metrics_trace_audited.csv.gz"
RECORD = "RESULTS_TRACE_AUDITED.md"
TENANTS = 8
COST_SCALE_USD = 0.01
EQ_MARGIN = 0.025
SEGMENT_SPLIT = 48  # windows 0-47: first coverage segment; 48-95: second
COLUMNS = ["total_cost_usd", "mean_violation", "mean_jain", "mean_excess", "tier_none_step_share", "steps"]
KEYS = ["system", "workload", "tenant_mix", "cluster_size", "rep"]

TREATMENT = "jcac_converged"
ARMS = [TREATMENT, "jcac_decoupled", "jcac_tier_floor", "hpa_fair_capped", "keda_fair_capped",
        "layered_small_tuned", "static_share"]
TESTS = {"TA-H1": "hpa_fair_capped", "TA-H2": "keda_fair_capped",
         "TA-H3": "layered_small_tuned", "TA-H4": "static_share"}
DESCRIPTIVE = [("never shed − JC", "jcac_tier_floor", TREATMENT),
               ("never shed − capped HPA", "jcac_tier_floor", "hpa_fair_capped")]


def load() -> pd.DataFrame:
    if not DB.exists():
        return pd.read_csv(EXPORT, float_precision="round_trip")[KEYS + COLUMNS]
    import duckdb

    con = duckdb.connect(str(DB), read_only=True)
    try:
        return con.execute(
            "select " + ", ".join(f"r.{c}" for c in KEYS) + ", "
            + ", ".join(f"m.{c}" for c in COLUMNS)
            + " from runs r join metrics m on r.run_id = m.run_id where r.status = 'valid'").fetchdf()
    finally:
        con.close()


def score_j(df: pd.DataFrame) -> pd.Series:
    return (df.total_cost_usd / (df.steps * TENANTS) / COST_SCALE_USD
            + 2.0 * df.mean_violation + 0.5 * (1.0 - df.mean_jain))


def complete_windows(df: pd.DataFrame) -> pd.DataFrame:
    """Listwise: keep a window only if every arm has a valid run there."""
    df = df[df.system.isin(ARMS)]
    have = df.groupby(DESIGN).system.nunique()
    keep = set(have[have == len(ARMS)].index)
    return df[[k in keep for k in zip(*(df[c] for c in DESIGN))]]


def ci(r: dict) -> str:
    return f"[{r['ci'][0]:+.4f}, {r['ci'][1]:+.4f}]"


def reading(r: dict) -> str:
    if r["ci"][1] < 0:
        return "a better"
    if r["ci"][0] > 0:
        return "b better"
    return "no difference shown"


def window_number(df: pd.DataFrame) -> pd.Series:
    return df.workload.str[-2:].astype(int)


def build(df: pd.DataFrame) -> str:
    n_all = df[DESIGN].drop_duplicates().shape[0]
    df = complete_windows(df).assign(J=lambda d: score_j(d))
    n = df[DESIGN].drop_duplicates().shape[0]
    L = ["# Real BurstGPT demand against the audited comparators", "",
         "Generated by `analysis_trace_audited.py`, frozen with `PREREG_TRACE_AUDITED.md`. Unit: the "
         "six-hour window (96 TRACE2 windows; one rep each), listwise complete. J uses each run's own "
         "scored steps. PASS = one-sided Wilcoxon at its Holm threshold AND the 95% bootstrap CI of the "
         f"mean ΔJ entirely below 0 ({BOOT_N:,} resamples, seed {BOOT_SEED}). Negative ΔJ = JC better.", "",
         f"## {n} of {n_all} windows complete", "",
         "| arm | J | cost $ | violation | excess | Jain | AI shed |", "|---|---:|---:|---:|---:|---:|---:|"]
    for arm in ARMS:
        s = df[df.system == arm]
        L.append(f"| `{arm}` | {s.J.mean():.4f} | {s.total_cost_usd.mean():.2f} | {s.mean_violation.mean():.4f} | "
                 f"{s.mean_excess.mean():.4f} | {s.mean_jain.mean():.4f} | {s.tier_none_step_share.mean():.1%} |")

    res = {hid: superiority(design_diffs(df, TREATMENT, b, "J")) for hid, b in TESTS.items()}
    holm = holm_bonferroni({hid: r["p"] for hid, r in res.items()}, ALPHA)
    L += ["", "## Confirmatory: TA-H1..H4 (one Holm family of 4)", "",
          "| id | b | windows | ΔJ = JC − b | 95% CI | JC better in | Wilcoxon p | Holm threshold | verdict | "
          "reading | Δexcess [95% CI] |", "|---|---|---:|---:|---|---:|---:|---:|---|---|---|"]
    for hid, b in TESTS.items():
        r = res[hid]
        ok = bool(holm[hid]["reject"] and r["ci"][1] < 0)
        g = superiority(design_diffs(df, TREATMENT, b, "mean_excess"))
        L.append(f"| **{hid}** | `{b}` | {r['n']} | {r['mean']:+.4f} | {ci(r)} | {r['better']:.0%} | {r['p']:.3g} | "
                 f"{holm[hid]['threshold']:.4f} | {'PASS' if ok else 'FAIL'} | {reading(r)} | "
                 f"{g['mean']:+.4f} {ci(g)} |")

    r = superiority(design_diffs(df, TREATMENT, "jcac_decoupled", "J"))
    eq = -EQ_MARGIN < r["ci"][0] and r["ci"][1] < EQ_MARGIN
    L += ["", f"## Equivalence within ±{EQ_MARGIN} J", "", "| id | a | b | ΔJ | 95% CI | equivalent? |",
          "|---|---|---|---:|---|---|",
          f"| TA-EQ | `{TREATMENT}` | `jcac_decoupled` | {r['mean']:+.4f} | {ci(r)} | "
          f"{'EQUIVALENT' if eq else 'not shown'} |"]

    L += ["", "## Descriptive contrasts (no test)", "", "| contrast | ΔJ | 95% CI | reading |", "|---|---:|---|---|"]
    for label, a, b in DESCRIPTIVE:
        d = superiority(design_diffs(df, a, b, "J"))
        L.append(f"| {label} | {d['mean']:+.4f} | {ci(d)} | {reading(d)} |")

    L += ["", "## Primary contrasts by coverage segment (descriptive)", "",
          "| contrast | segment 1 (windows 0–47) ΔJ [95% CI] | segment 2 (windows 48–95) ΔJ [95% CI] |",
          "|---|---|---|"]
    first = window_number(df) < SEGMENT_SPLIT
    for hid, b in TESTS.items():
        cells = []
        for part in (df[first], df[~first]):
            d = design_diffs(part, TREATMENT, b, "J")
            cells.append(f"{d.mean():+.4f} {ci(superiority(d))}" if len(d) > 1 else "n/a")
        L.append(f"| JC − `{b}` | {cells[0]} | {cells[1]} |")
    return "\n".join(L) + "\n"


def main() -> int:
    out = record_path(RECORD)
    out.write_text(build(load()), encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
