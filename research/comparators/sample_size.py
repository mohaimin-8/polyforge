"""Paired workloads needed for the planned tests, from the WP9 pilot's
variances (programme 2, design input for WP12/WP13; EXPLORATORY).

For each plant and comparator, sigma_d is the standard deviation over the
evaluation workloads of J(comparator) - J(joint) (granularity `overall`).
With alpha = 0.05 and power 0.9 (plan, WP12):
  superiority, smallest effect Delta: n = ((1.645 + 1.282) sigma_d / Delta)^2
  equivalence within +/- eps, true difference 0: n = ((1.645 + 1.645) sigma_d / eps)^2
Delta and eps are stated as shares of the joint planner's mean J. The pilot
is reduced (16 configurations per arm, 24 workloads), so sigma_d is itself
uncertain; the counts are a planning input, not a registered design.

    python sample_size.py      # writes SAMPLE_SIZE.md
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
SHARES = (0.01, 0.02, 0.05)
Z_SUP = 1.645 + 1.282
Z_EQ = 1.645 + 1.645


def main() -> int:
    L = ["# Paired workloads needed for the planned tests (WP9 pilot variances; exploratory)", "",
         "Generated by `research/comparators/sample_size.py`. alpha 0.05, power 0.9; effects as shares of the "
         "joint planner's mean J. The population's evaluation half holds 120 workloads.", "",
         "| plant | comparator | mean J(comp) - J(joint) | sigma_d | "
         + " | ".join(f"superiority / equivalence at {s:.0%}" for s in SHARES) + " |",
         "|---|---|---:|---:|" + "---:|" * len(SHARES)]
    for path in sorted(HERE.glob("pilot/plant*_own_*/runs.csv.gz")):
        plant = path.parent.name.split("_")[0].replace("plant", "")
        runs = pd.read_csv(path, float_precision="round_trip")
        runs = runs[(runs.phase == "evaluation") & runs.granularities.str.contains("overall")]
        wide = runs.pivot_table(index="workload", columns="arm", values="J")
        jbar = wide.joint.mean()
        for comp in (c for c in wide.columns if c != "joint"):
            d = (wide[comp] - wide.joint).dropna()
            sd = d.std(ddof=1)
            cells = []
            for share in SHARES:
                delta = share * jbar
                cells.append(f"{math.ceil((Z_SUP * sd / delta) ** 2)} / {math.ceil((Z_EQ * sd / delta) ** 2)}")
            L.append(f"| {plant} | {comp} | {d.mean():+.4f} | {sd:.4f} | " + " | ".join(cells) + " |")
    L += ["", "Reading: equivalence within 2% of J needs at most 76 paired workloads for every comparator "
          "(the per-knob planner in plant A is the noisiest); within 1%, everything but that pair fits in 120.", ""]
    (HERE / "SAMPLE_SIZE.md").write_text("\n".join(L), encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
