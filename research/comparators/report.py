"""Markdown report of one WP9 tuning run (tune.py writes it)."""

from __future__ import annotations

import math

import numpy as np

import protocol
from protocol import CLASS_RULE, bootstrap_ci, evaluation_table


def _f(x: float, digits: int = 4) -> str:
    return "n/a" if x is None or not math.isfinite(x) else f"{x:.{digits}f}"


def _ci(values) -> str:
    lo, hi = bootstrap_ci(values)
    return f"{_f(float(np.mean(values)))} [{_f(lo)}, {_f(hi)}]" if len(values) else "n/a"


def _params(params: dict) -> str:
    return ", ".join(f"{k}={v:.4g}" if isinstance(v, float) else f"{k}={v}" for k, v in params.items())


def reduced(meta: dict) -> bool:
    """True unless the run is the registered protocol's full size."""
    return (meta["configs"] < 64 or meta["steps"] < 120 or meta["tuning_n"] < meta["tuning_total"]
            or meta["evaluation_n"] < meta["evaluation_total"])


def render(meta: dict, arms_meta: dict, configs: dict, selection: dict, rows: list[dict],
           references: list[dict]) -> str:
    L = [f"# WP9 tuning: plant {meta['plant']}, tenant mix {meta['mix']}, {meta['cluster_size']} cluster", ""]
    if reduced(meta):
        L += ["**REDUCED RUN: a pipeline check, not the registered protocol and not a result.**", ""]
    L += ["Generated by `research/comparators/tune.py`. Programme 2, WP9. Exploratory until registered.", "",
          "| setting | value |", "|---|---|"]
    for key in ("plant", "mix", "cluster_size", "steps", "configs", "include_default", "seed", "budget",
                "quality_weight", "granularity", "tuning_n", "evaluation_n"):
        L.append(f"| {key} | {meta[key]} |")
    L += ["", f"Workload class rule: {CLASS_RULE}.", "",
          "| half | " + " | ".join(protocol.CLASSES) + " |", "|---|" + "---:|" * len(protocol.CLASSES)]
    for half in ("tuning", "evaluation"):
        counts = meta["class_counts"][half]
        L.append(f"| {half} | " + " | ".join(str(counts.get(c, 0)) for c in protocol.CLASSES) + " |")
    L += _arms_section(arms_meta)
    L += _selection_section(configs, selection, rows)
    for granularity in meta["granularities"]:
        L += _evaluation_section(rows, granularity)
    if "overall" in meta["granularities"] and "per_class" in meta["granularities"]:
        L += _granularity_gain(rows)
    L += _reference_section(rows, references, meta)
    L += _errors_section(rows + references)
    L += ["## Caveats", "",
          "- Exploratory: nothing here is registered; the class rule, the spaces and the 64-configuration "
          "budget are fixed in `research/comparators/` before any result.",
          "- Paired comparisons share demand: every arm and configuration of a workload saw the same "
          "seeded demand (harness shared seeds).",
          "- LB1, LB2 and UB assume the planners' move limits (+/-2 replicas, one cache level per "
          "interval). The default-behaviour HPA, the cluster-cap trim and the budget gate may move "
          "further, and the planners' infeasible-lattice fallback jumps to the floor; only LB0 bounds "
          "every arm. `clamp viol.` is the share of tenant-steps that left the limits.",
          ""]
    return "\n".join(L)


def _arms_section(arms_meta: dict) -> list[str]:
    L = ["", "## Arms and parameter spaces", ""]
    for name, a in arms_meta.items():
        L += [f"**{name}**: {a['description']}. Maps to: {a['maps_to']}.", ""]
        if a["space"]:
            L += ["| parameter | range | default |", "|---|---|---|"]
            L += [f"| `{p['name']}` | {p['range']} | {p['default']} |" for p in a["space"]]
            L.append("")
    return L


def _selection_section(configs: dict, selection: dict, rows: list[dict]) -> list[str]:
    L = ["## Selected configurations (tuning half)", "",
         "| arm | scope | config | tuning J | n | default's tuning J | median over configs |",
         "|---|---|---:|---:|---:|---:|---:|"]
    tuning = [r for r in rows if r["phase"] == "tuning"]
    for name, picks in selection.items():
        per_config: dict[int, list[float]] = {}
        for r in tuning:
            if r["arm"] == name:
                per_config.setdefault(int(r["config"]), []).append(r["J"])
        means = [float(np.mean(v)) for v in per_config.values() if all(math.isfinite(x) for x in v)]
        default = per_config.get(0)
        default_j = float(np.mean(default)) if default and all(math.isfinite(x) for x in default) else None
        median = float(np.median(means)) if means else None
        scopes = [("overall", picks["overall"])] + sorted(picks["per_class"].items())
        for scope, pick in scopes:
            if pick is None:
                L.append(f"| {name} | {scope} | none qualified | | | | |")
                continue
            L.append(f"| {name} | {scope} | {pick.config} | {_f(pick.mean_J)} | {pick.n} | "
                     f"{_f(default_j) if scope == 'overall' else ''} | {_f(median) if scope == 'overall' else ''} |")
    L += ["", "Selected parameters:", ""]
    for name, picks in selection.items():
        for scope, pick in [("overall", picks["overall"])] + sorted(picks["per_class"].items()):
            if pick is not None:
                L.append(f"- {name} / {scope} (config {pick.config}): {_params(configs[name][pick.config])}")
    L.append("")
    return L


def _evaluation_section(rows: list[dict], granularity: str) -> list[str]:
    table = evaluation_table(rows, granularity)
    L = [f"## Evaluation half, granularity `{granularity}`", "",
         "| arm | n | J mean [95% CI] | cost | violation | unfairness | quality | budget overrun | "
         "clamp viol. |", "|---|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for name, by_wl in table.items():
        ok = [r for r in by_wl.values() if math.isfinite(r["J"])]
        if not ok:
            L.append(f"| {name} | 0 | n/a | | | | | | |")
            continue

        def mean(key: str) -> str:
            return _f(float(np.mean([r[key] for r in ok])))

        L.append(f"| {name} | {len(ok)} | {_ci([r['J'] for r in ok])} | {mean('cost_term')} | "
                 f"{mean('violation_term')} | {mean('unfairness_term')} | {mean('quality_term')} | "
                 f"{mean('budget_overrun_step_share')} | {mean('clamp_violation_step_share')} |")
    fallback = sum(1 for by_wl in table.values() for r in by_wl.values() if r.get("per_class_fallback"))
    if granularity == "per_class" and fallback:
        L += ["", f"{fallback} evaluation runs used the overall configuration: their class had no tuning workload."]
    if "joint" in table:
        L += ["", "Paired difference J(arm) - J(joint) over shared workloads (positive: the joint planner is "
              "better):", "", "| arm | n | mean [95% CI] | joint better / worse |", "|---|---:|---:|---:|"]
        joint = table["joint"]
        for name, by_wl in table.items():
            if name == "joint":
                continue
            shared = [w for w in by_wl if w in joint and math.isfinite(by_wl[w]["J"])
                      and math.isfinite(joint[w]["J"])]
            diffs = [by_wl[w]["J"] - joint[w]["J"] for w in shared]
            if diffs:
                L.append(f"| {name} | {len(diffs)} | {_ci(diffs)} | {sum(d > 0 for d in diffs)} / "
                         f"{sum(d < 0 for d in diffs)} |")
    L.append("")
    return L


def _granularity_gain(rows: list[dict]) -> list[str]:
    overall = evaluation_table(rows, "overall")
    per_class = evaluation_table(rows, "per_class")
    L = ["## What per-class tuning buys", "", "J(overall configuration) - J(per-class configuration) on the "
         "evaluation half (positive: per-class tuning helps).", "",
         "| arm | n | mean [95% CI] |", "|---|---:|---:|"]
    for name in overall:
        shared = [w for w in overall[name] if w in per_class.get(name, {})]
        diffs = [overall[name][w]["J"] - per_class[name][w]["J"] for w in shared
                 if math.isfinite(overall[name][w]["J"]) and math.isfinite(per_class[name][w]["J"])]
        if diffs:
            L.append(f"| {name} | {len(diffs)} | {_ci(diffs)} |")
    L.append("")
    return L


def _reference_section(rows: list[dict], references: list[dict], meta: dict) -> list[str]:
    if not meta["references_requested"]:
        return []
    L = ["## Reference lines (WP1, evaluation half)", ""]
    if meta["quality_weight"] > 0.0:
        return L + ["Not computed: the bounds of `research/theory/clairvoyant.py` do not price answer "
                    "quality, so they bound nothing under a quality-priced J.", ""]
    ok = [r for r in references if not r.get("error")]
    if not ok:
        return L + ["No reference line could be computed (see errors).", ""]
    L += ["| line | mean over workloads | n |", "|---|---:|---:|"]
    for key, label in (("static", "static best (hindsight, equal share)"), ("lb0", "LB0 (any controller)"),
                       ("lb1", "LB1 (move limits, no caps)"), ("lb2", "LB2 (move limits, caps)"),
                       ("ub", "UB (achievable, move limits, caps)")):
        L.append(f"| {label} | {_f(float(np.mean([r[key] for r in ok])))} | {len(ok)} |")
    ref = {r["workload"]: r for r in ok}
    L += ["", "Normalised regret, ratio of means over the workloads with a reference: (J - LB) / "
          "(static - LB).", "", "| arm | granularity | n | regret vs LB2 | regret vs LB0 |", "|---|---|---:|---:|---:|"]
    for granularity in meta["granularities"]:
        for name, by_wl in evaluation_table(rows, granularity).items():
            shared = [w for w in by_wl if w in ref and math.isfinite(by_wl[w]["J"])]
            if not shared:
                continue
            j = float(np.mean([by_wl[w]["J"] for w in shared]))
            static = float(np.mean([ref[w]["static"] for w in shared]))
            cells = []
            for lb in ("lb2", "lb0"):
                low = float(np.mean([ref[w][lb] for w in shared]))
                cells.append(_f((j - low) / (static - low)) if static > low else "n/a")
            L.append(f"| {name} | {granularity} | {len(shared)} | {cells[0]} | {cells[1]} |")
    L.append("")
    return L


def _errors_section(rows: list[dict]) -> list[str]:
    errors = [r for r in rows if r.get("error")]
    if not errors:
        return ["## Errors", "", "None.", ""]
    L = ["## Errors", "", f"{len(errors)} runs failed; their configurations were excluded from selection.", ""]
    for r in errors[:20]:
        L.append(f"- {r['phase']} {r.get('arm', '')} config {r.get('config', '')} {r['workload']}: {r['error']}")
    L.append("")
    return L
