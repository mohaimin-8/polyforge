"""Does the lowest HPA target of the twin's tuning grid bind? (programme 2, WP17; a check, not a prediction)

twin_predict.py tunes each HPA arm's target on separate draws over
twin_pilot.TARGETS, whose lowest value is 0.1. Wherever the committed
predictions chose that edge, this evaluates the same tuning objective (mean J
over the tuning draws) at BELOW as well. The edge binds when a lower target
has a lower J: the arm would then be tuned worse than it could be, and A4's
predicted gain over it inflated.

    python grid_edge.py --calibration calibration.json --predictions predictions.json --out GRID_EDGE.md
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import twin  # noqa: E402
import twin_pilot as tp  # noqa: E402
import workloads  # noqa: E402
from service_plant import from_calibration  # noqa: E402

BELOW = (0.05, 0.075)
LIVE_ARM = {"cpu": "A1", "rate": "A2"}   # HPA on CPU utilisation, KEDA on the request rate


def binds(scores: dict[float, float], edge: float) -> bool:
    """True when a target below the grid's edge has a lower mean J than the edge."""
    lower = [j for t, j in scores.items() if t < edge]
    return bool(lower) and min(lower) < scores[edge]


def mean_j(plant, metric: str, vpa: str, target: float, tune: list) -> float:
    return float(np.mean([twin.run(twin.HpaVpa(metric, plant, vpa, target=target), plant, rates)["J"]
                          for _, _, rates in tune]))


def check(plant, tuned: dict) -> list[dict]:
    """One row per (volatility, HPA arm) whose committed target is the grid's edge."""
    edge, rows = min(tp.TARGETS), []
    for sigma in workloads.VOLATILITIES:
        tune = tp.draws(plant, 1, sigma, tp.TUNING_SEEDS)
        for metric, vpa in tp.HPA_ARMS:
            if tuned[str(sigma)][f"{metric}_{vpa}"] != edge:
                continue
            scores = {t: mean_j(plant, metric, vpa, t, tune) for t in (*BELOW, edge)}
            rows.append({"sigma": sigma, "arm": f"{metric}_{vpa}", "live_arm": LIVE_ARM[metric], "scores": scores,
                         "binds": binds(scores, edge), "j_lower_by": 1 - min(scores.values()) / scores[edge]})
    return rows


def report(rows: list[dict], edge: float) -> str:
    cols = [*BELOW, edge]
    L = ["# WP17: does the twin's tuning grid edge bind?", "",
         "Generated by `research/hvpa/grid_edge.py` on the committed calibration and predictions. A check, not a "
         f"prediction: each HPA arm tuned to the grid's lowest target ({edge:g}) is scored at lower targets too, "
         "on the tuning draws, with the tuning objective (mean J).", "",
         "| volatility | HPA arm | live arm | " + " | ".join(f"J at {t:g}" for t in cols) + " | edge binds | J lower by |",
         "|---:|---|---|" + "---:|" * len(cols) + "---|---:|"]
    for r in rows:
        L.append(f"| {r['sigma']:g} | {r['arm']} | {r['live_arm']} | "
                 + " | ".join(f"{r['scores'][t]:.4f}" for t in cols)
                 + f" | {'yes' if r['binds'] else 'no'} | {r['j_lower_by']:.2%} |")
    bound = [r for r in rows if r["binds"]]
    L += ["", f"{len(rows)} arms at the edge; it binds for {len(bound)}"
          + (": " + ", ".join(f"{r['arm']} at volatility {r['sigma']:g} ({r['live_arm']})" for r in bound)
             if bound else "") + ".", ""]
    return "\n".join(L)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--calibration", type=Path, default=HERE / "calibration.json")
    ap.add_argument("--predictions", type=Path, default=HERE / "predictions.json")
    ap.add_argument("--out", type=Path, default=HERE / "GRID_EDGE.md")
    args = ap.parse_args(argv)
    plant = from_calibration(args.calibration)
    tuned = json.loads(args.predictions.read_text(encoding="utf-8"))["tuned_targets"]
    text = report(check(plant, tuned), min(tp.TARGETS))
    args.out.write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
