"""Tier price and answer quality per request from RouterBench (programme 2, WP7, mode A).

RouterBench (Hu et al., arXiv:2403.12031v2, March 2024) records, for 36,497
prompts (0-shot file) and 11 LLMs, each answer's score and its estimated
cost: proprietary models at their API prices, open models at Together AI's,
at the time of the release. Those dated prices are the only per-request
prices this project has; they are not current prices.

Rule (stated before looking at the result): small = the cheapest model by
mean cost per prompt, large = the dearest, mid = the model whose mean cost is
closest in log to the geometric mean of the two. All 11 are tabulated so the
choice is visible. Quality = mean score with a Wilson 95% interval when
scores are 0/1 (a bootstrap interval otherwise). The 5-shot file is the
robustness check.

The per-prompt table is not committed (the dataset states no licence); the
aggregates are, in `data/tier_summary.json` and `TIERS.md`.

    python tiers.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))

from safe_load import load  # noqa: E402

Z = 1.959963984540054
SEED = 20261112


def models(df: pd.DataFrame) -> list[str]:
    return sorted({c.split("|")[0] for c in df.columns if c.endswith("|total_cost")})


def wilson(k: float, n: int) -> tuple[float, float]:
    p = k / n
    centre = (p + Z * Z / (2 * n)) / (1 + Z * Z / n)
    half = Z * math.sqrt(p * (1 - p) / n + Z * Z / (4 * n * n)) / (1 + Z * Z / n)
    return centre - half, centre + half


def summary(df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    rng = np.random.default_rng(SEED)
    for m in models(df):
        score = pd.to_numeric(df[m], errors="coerce")
        cost = pd.to_numeric(df[f"{m}|total_cost"], errors="coerce")
        ok = score.notna() & cost.notna()
        s, c = score[ok].to_numpy(float), cost[ok].to_numpy(float)
        binary = bool(np.isin(s, (0.0, 1.0)).all())
        if binary:
            lo, hi = wilson(s.sum(), len(s))
        else:
            boot = s[rng.integers(0, len(s), (2000, len(s)))].mean(axis=1)
            lo, hi = np.percentile(boot, [2.5, 97.5])
        rows.append({"model": m, "n": int(ok.sum()), "binary_scores": binary,
                     "mean_cost_usd": float(c.mean()), "p50_cost_usd": float(np.median(c)),
                     "p90_cost_usd": float(np.percentile(c, 90)),
                     "quality": float(s.mean()), "quality_lo": float(lo), "quality_hi": float(hi)})
    return pd.DataFrame(rows).sort_values("mean_cost_usd").reset_index(drop=True)


def choose(table: pd.DataFrame) -> dict[str, str]:
    small = table.iloc[0].model
    large = table.iloc[-1].model
    target = math.sqrt(table.iloc[0].mean_cost_usd * table.iloc[-1].mean_cost_usd)
    inner = table.iloc[1:-1]
    mid = inner.iloc[(np.log(inner.mean_cost_usd) - math.log(target)).abs().argmin()].model
    return {"small": small, "mid": mid, "large": large}


def report(tables: dict[str, pd.DataFrame], tiers: dict[str, str]) -> str:
    L = ["# Tier price and answer quality per request (programme 2, WP7, mode A)", "",
         "Generated by `research/tierquality/tiers.py` from RouterBench (Hu et al., arXiv:2403.12031v2), "
         "loaded with a restricted unpickler and checked against the published SHA-256. Costs are "
         "RouterBench's estimates at its release (March 2024): proprietary models at their API prices "
         "then, open models at Together AI's. They are dated prices, not current ones.", "",
         "Rule fixed before the result: small = cheapest by mean cost, large = dearest, mid = closest in "
         "log to their geometric mean.", ""]
    for name, t in tables.items():
        L += [f"## {name}", "", "| model | prompts | mean cost $ | median $ | p90 $ | quality [95% CI] | tier |",
              "|---|---:|---:|---:|---:|---|---|"]
        rev = {v: k for k, v in tiers.items()}
        for r in t.itertuples():
            L.append(f"| {r.model} | {r.n:,} | {r.mean_cost_usd:.3g} | {r.p50_cost_usd:.3g} | {r.p90_cost_usd:.3g} | "
                     f"{r.quality:.3f} [{r.quality_lo:.3f}, {r.quality_hi:.3f}] | {rev.get(r.model, '')} |")
        L.append("")
    t = tables["0-shot"].set_index("model")
    s, m, l = (t.loc[tiers[k]] for k in ("small", "mid", "large"))
    L += [f"Mode A tiers (0-shot): small {tiers['small']} ${s.mean_cost_usd:.3g}, mid {tiers['mid']} "
          f"${m.mean_cost_usd:.3g}, large {tiers['large']} ${l.mean_cost_usd:.3g} per request; price ratio "
          f"1 : {m.mean_cost_usd / s.mean_cost_usd:.2f} : {l.mean_cost_usd / s.mean_cost_usd:.2f}; quality "
          f"{s.quality:.3f} / {m.quality:.3f} / {l.quality:.3f}.", ""]
    return "\n".join(L)


def main() -> int:
    tables = {"0-shot": summary(load("routerbench_0shot.pkl")), "5-shot": summary(load("routerbench_5shot.pkl"))}
    tiers = choose(tables["0-shot"])
    out = {"source": "RouterBench (arXiv:2403.12031v2), costs at release, March 2024", "tiers": tiers,
           "tables": {k: v.to_dict(orient="records") for k, v in tables.items()}}
    (HERE / "data").mkdir(exist_ok=True)
    (HERE / "tier_summary.json").write_text(json.dumps(out, indent=1), encoding="utf-8")
    text = report(tables, tiers)
    (HERE / "TIERS.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
