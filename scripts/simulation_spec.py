"""Write docs/SIMULATION_SPEC.md: every parameter the conference paper's
simulation campaigns depend on, read from the code that runs them.

Nothing here is typed by hand: the tables are rendered from the live
constants (model.py, controller.py, workloads.py, systems.py, the tuned
baseline files), and the demand-shape and plant functions are quoted from
their source, so the document cannot drift from what ran.

    python scripts/simulation_spec.py           # rewrite docs/SIMULATION_SPEC.md
    python scripts/simulation_spec.py --check   # exit 1 if it is stale (eval/tests asserts this)
"""

from __future__ import annotations

import argparse
import dataclasses
import inspect
import sys
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "eval"))
from harness import systems, workloads  # noqa: E402  (puts research/jcac_sim on the path)

import controller  # noqa: E402
import model  # noqa: E402

OUT = REPO / "docs" / "SIMULATION_SPEC.md"
PAPER_WORKLOADS = ["crud_bursty", "crud_steady", "ai_cacheable", "ai_uncacheable", "agentic"]
HELDOUT_WORKLOADS = ["mmpp_crud", "mmpp_mixed"]
PAPER_ARMS = ["jcac_converged", "jcac_decoupled", "jcac_knobwise", "jcac_tier_floor", "hpa_fair_capped",
              "keda_fair_capped", "layered_small_tuned", "layered_costaware_tuned", "static_share"]
LEVEL_ARMS = ["jcac_level", "jcac_level_decoupled", "jcac_level_ratchet", "jcac_level_ratchet_decoupled",
              "layered_small_level_capped", "layered_small_level_gated", "hpa_level_capped", "keda_level_capped",
              "layered_costaware_gpu_gated", "layered_costaware_gpu_capped", "layered_small_gpu_gated",
              "hpa_gpu_capped"]


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return out


def code(fn) -> list[str]:
    return ["```python", inspect.getsource(fn).rstrip(), "```"]


def arm_rows(arms: list[str]) -> list[tuple]:
    rows = []
    for arm in arms:
        s = systems.SYSTEMS[arm]
        rows.append((arm, s.controller, s.params or "", s.static_cache_mb or "", s.description.replace("|", "/")))
    return rows


def render() -> str:
    L = ["# Simulation specification", "",
         "Generated by `scripts/simulation_spec.py` from the code that runs the campaigns; regenerate it after "
         "any change. Units: rates in requests/s, latency in ms, money in simulated USD.", ""]

    L += ["## Control loop and planner", ""]
    L += table(["parameter", "value"], [
        ("control interval", f"{model.CONTROL_INTERVAL_S} s"),
        ("replica moves per interval (published lattice)", controller.DELTA_REPLICAS),
        ("replica moves per interval (wide lattice, WIDTH)", f"{controller.WIDE_DELTA_REPLICAS[0]}..{controller.WIDE_DELTA_REPLICAS[-1]}"),
        ("cache levels (MB)", model.CACHE_LEVELS_MB),
        ("tiers", ", ".join(model.TIER_COST_USD_PER_REQ)),
        ("objective weights (alpha, beta, gamma)", tuple(dataclasses.asdict(controller.Weights()).values())),
        ("switching penalty lambda (per changed knob)", controller.SWITCH_PENALTY),
        ("cost scale c0 (per tenant-step)", f"${controller.COST_SCALE_USD}"),
    ])
    L += ["", "Forecaster (`controller.Forecast`, default `trend`):", ""] + code(controller.Forecast)

    L += ["", "## Plant", ""]
    L += table(["parameter", "value"], [
        ("replica capacity", f"{model.REPLICA_CAPACITY_WU} work units/s"),
        ("work units per request kind", model.WORK_UNITS),
        ("cacheable fraction per AI kind", model.CACHEABLE_FRACTION),
        ("cache hit curve", f"h(c) = {model.CACHE_HIT_MAX} c / (c + {model.CACHE_HALF_MB}) of the cacheable share"),
        ("cache-hit latency", f"{model.CACHE_HIT_LATENCY_MS} ms"),
        ("p95 / mean factor", model.P95_FACTOR),
        ("saturation utilisation / congestion cap", f"{model.SATURATION_RHO} / {model.MAX_CONGESTION}"),
        ("replica cost", f"${model.REPLICA_COST_USD_HR} per replica-hour"),
        ("cache memory cost", f"${model.MEM_COST_USD_GB_HR} per GB-hour"),
        ("SLO base targets", model.SLO_BASE_MS),
        ("SLO class factors", model.SLO_CLASS_FACTOR),
    ])
    L += ["", "Model tiers (price per request that misses the cache; base latency per AI kind; quality index "
          "= mean of 11 Qwen2.5 instruction-tuned benchmark scores / 100, small = 0.5B, mid = 3B, large = 7B):", ""]
    kinds = list(model.TIER_BASE_LATENCY_MS)
    rows = []
    for tier, price in model.TIER_COST_USD_PER_REQ.items():
        lat = ("flat " + f"{model.NO_TIER_LATENCY_MS:g}" if tier == "none"
               else ", ".join(f"{k} {model.TIER_BASE_LATENCY_MS[k][tier]:g}" for k in kinds))
        rows.append((tier, f"{price:g}", lat, f"{model.TIER_QUALITY[tier]:.3f}"))
    L += table(["tier", "price $", "base latency (ms)", "quality index"], rows)
    L += ["", "Congestion and per-step evaluation (latency, violation, excess, cost):", ""]
    L += code(model.congestion) + [""] + code(model.evaluate_step)

    L += ["", "## Workloads", "", "Per-tenant base rates at scale 1.0, multiplied by the class's demand shape:", ""]
    rows = []
    for name in PAPER_WORKLOADS + HELDOUT_WORKLOADS:
        cls = workloads.WORKLOAD_CLASSES[name]
        rows.append((name, cls.shape, cls.base_rps, cls.crud_base_ms,
                     "held-out (HELDOUT)" if name in HELDOUT_WORKLOADS else "main matrix"))
    L += table(["class", "shape", "base rates (rps)", "CRUD base ms", "used in"], rows)
    L += ["", "Demand shapes (periodic classes; per-tenant phase drawn uniformly from the run seed):", ""]
    L += code(workloads._shape_factor)
    L += ["", f"Markov-modulated shape (held-out classes): low {workloads.MMPP_LOW}, high {workloads.MMPP_HIGH}, "
          f"P(low->high) {workloads.MMPP_P_UP}, P(high->low) {workloads.MMPP_P_DOWN}, mean-one lognormal noise "
          f"sigma {workloads.MMPP_NOISE_SIGMA}, started from the stationary distribution:", ""]
    L += code(workloads.mmpp_factors)
    L += ["", "Arrival noise: every run Poisson-resamples each bucket's request counts from its seed "
          "(`simulate.jitter_buckets`); with shared seeds, all arms of a design point see identical demand.", ""]

    L += ["## Tenant mixes (eight tenants each)", ""]
    rows = []
    for mix in ["uniform", "premium_heavy", "besteffort_heavy", "whale"]:
        slots = workloads.TENANT_MIXES[mix]
        rows.append((mix, "; ".join(f"{s.slo_class} ${s.budget_usd:g}/h x{s.scale:g}" for s in slots)))
    L += table(["mix", "tenants (SLO class, hourly budget, demand scale)"], rows)

    L += ["", "## Cluster sizes", ""]
    rows = [(n, s.limits_replicas, s.limits_cache_mb, s.replica_max)
            for n, s in workloads.CLUSTER_SIZES.items() if n in ("small", "medium", "large")]
    L += table(["size", "replica cap (all tenants)", "cache cap MB (all tenants)", "per-tenant replica cap"], rows)

    header = ["arm", "controller", "params", "static cache MB", "description"]
    L += ["", "## Arms", ""]
    L += table(header, arm_rows(PAPER_ARMS))
    L += ["", "Level-field arms (`PREREG_LEVEL`, `PREREG_LEVEL_LAG`, `PREREG_LEVEL2`):", ""]
    L += table(header, arm_rows(LEVEL_ARMS))
    L += ["", "Tuned baseline parameters (`eval/baselines/tuned.yaml`, `eval/baselines/tuned_arms.yaml`):", "",
          "```yaml", yaml.safe_dump(systems.tuned_params(), sort_keys=True).rstrip(),
          "---", yaml.safe_dump(systems.tuned_arms(), sort_keys=True).rstrip(), "```", ""]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Write or check docs/SIMULATION_SPEC.md.")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if the document is stale")
    args = ap.parse_args(argv)
    text = render()
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale: run python scripts/simulation_spec.py", file=sys.stderr)
            return 1
        print(f"{OUT} is current")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
