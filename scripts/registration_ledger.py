"""Write docs/REGISTRATION_LEDGER.md: when each registered campaign's protocol
was committed, when its first run started, and the gap between them.

Derived, not hand-written: the gaps come from `check_prereg_timing.audit()`
(the same reading the timing gate applies, with its host-clock rule), and the
protocol commits from git. Needs the raw DuckDBs or committed exports that
carry run timestamps; a campaign without them is listed as not judged.

    python scripts/registration_ledger.py
"""

from __future__ import annotations

import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "scripts"))
import check_prereg_timing as cpt  # noqa: E402

OUT = REPO / "docs" / "REGISTRATION_LEDGER.md"
# The campaigns the conference paper reports, in its order.
PAPER = ["matrix_fair_j", "matrix_retuned", "matrix_jointness", "matrix_actuation", "matrix_quality",
         "matrix_heldout", "matrix_width_published", "matrix_width_coupled", "matrix_width_live",
         "matrix_reviewer_wide", "matrix_reviewer_live", "matrix_trace_audited",
         "matrix_cache_measured", "matrix_cache_published", "matrix_cache_high"]


def first_commit(stem: str) -> tuple[str, str]:
    out = subprocess.run(["git", "log", "--reverse", "--format=%h %ct", "--",
                          f"research/analysis/{stem}.md"], cwd=REPO, capture_output=True,
                         text=True).stdout.split("\n")[0].split()
    if not out:
        return "-", "-"
    when = datetime.fromtimestamp(int(out[1]), tz=timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    return out[0], when


def fmt_gap(gap_s: float | None) -> str:
    if gap_s is None:
        return "not judged"
    minutes = gap_s / 60.0
    return f"{minutes:+.1f} min" if abs(minutes) < 120 else f"{minutes / 60.0:+.1f} h"


def main() -> int:
    rows = {r["name"]: r for r in cpt.audit()}
    lines = ["# Registration ledger", "",
             "Generated by `scripts/registration_ledger.py` from the git history and the timing gate "
             "(`scripts/check_prereg_timing.py`, same host-clock rule). *Gap* = first run minus the "
             "protocol's first commit; positive means the protocol was committed first. Commit ids are "
             "those of the current history (see `COMMIT_MAP.md`).", "",
             "## Campaigns reported in the conference paper", "",
             "| campaign | protocol | protocol commit | committed (UTC) | gap to first run | timing verdict |",
             "|---|---|---|---|---:|---|"]
    for name in PAPER:
        r = rows.get(name)
        if r is None:
            continue
        sha, when = first_commit(r["prereg"])
        lines.append(f"| `{name}` | `{r['prereg']}` | `{sha}` | {when} | {fmt_gap(r['gap_s'])} | {r['verdict']} |")
    others = [r for n, r in sorted(rows.items()) if n not in PAPER]
    disclosed = [r for r in others if r["verdict"].startswith("disclosed")]
    judged = [r for r in rows.values() if r["gap_s"] is not None]
    lines += ["", "## Programme", "",
              f"- Campaigns with a registered protocol: {len(rows)}; judged (run timestamps available): "
              f"{len(judged)}.",
              f"- Runs before their protocol: {sum(1 for r in judged if r['gap_s'] < 0)}, every one disclosed "
              "in its protocol:"]
    for r in disclosed:
        lines.append(f"  - `{r['name']}` (`{r['prereg']}`): {fmt_gap(r['gap_s'])} — {cpt.DISCLOSED.get(r['name'], '')}")
    lines.append("")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
